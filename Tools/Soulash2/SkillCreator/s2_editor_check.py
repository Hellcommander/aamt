#!/usr/bin/env python3
"""Generate a TestBot script that opens a mod animation in the F3 editor, adds/removes particle
flags through the editor UI, and snapshots form + preview. NEVER presses Accept (1710,1035), the
only control that writes the animation JSON, and leaves with F4 (no save prompt).

Layout (1920x1080) mapped by TestBot runs 20261106-034155Z .. -063744Z:
  main menu Mods 244,202; mods search 555,228; first mod row 535,274; Edit 1428,843
  F3 animation search 220,570; first filtered row edit icon 337,609
  particle n edit icon 1557, 585 + 30*(n-1)
  particle form Settings input 1260,771 -> dropdown of flags NOT yet set, substring filtered, in bit
  order; first option 1260,801. Active flags listed at y 802 + 29*k, remove X at x 1392: in bit order
  when the particle form opens, but flags added afterwards are APPENDED (so remove before adding).
  After a pick the dropdown reopens UNFILTERED ("Repeat every square" on top): close it with Escape,
  never with a click (a click there added a stray flag, run 20261106-083650Z).
  Particle form close X 1484,75; with it closed the preview (caster + target row, left of the
  animation form) is visible and plays on a loop, and it DOES reflect unsaved edits.
  Re-opening an animation from the list reloads it from the JSON: unsaved edits are dropped.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import s2_particle_flags as pf

SEARCH_ROW_EDIT = (337, 609)
SETTINGS_INPUT = (1260, 771)
FIRST_OPTION = (1260, 801)
PARTICLE_FORM_CLOSE = (1484, 75)
ACTIVE_X = 1392
ACTIVE_Y0 = 802
ROW = 29
LIST_ROW = 28  # animation list rows below the search: 609, 637, 665 (run 20261106-085313Z)


def particle_icon(n: int) -> tuple:
    return (1557, 585 + 30 * (n - 1))


@dataclass
class ParticleEdit:
    particle: int                      # 1-based, as in the editor
    current: int                       # flags value in the JSON the game loaded
    set_bits: List[int] = field(default_factory=list)
    clear_bits: List[int] = field(default_factory=list)


@dataclass
class AnimCheck:
    search: str                        # text for the F3 animation search (first row must be this animation)
    edits: List[ParticleEdit]
    label: str = ""
    row: int = 0                       # 0-based row in the filtered list (see list_row)


def filter_word(bit: int) -> str:
    """One space-free word that makes `bit` the FIRST dropdown option.

    Typing a space into the Settings field picks the highlighted option (run 20261106-083650Z:
    "Fade while life is ending" added Repeat every square + Fade), so type a single word. Options are
    in bit order, so it suffices that no lower-bit label contains the word."""
    label = pf.FLAGS[bit][2]
    lower = [f[2].lower() for f in pf.FLAGS[:bit]]
    for w in sorted(set(label.split()), key=len, reverse=True):
        if not any(w.lower() in l for l in lower):
            return w
    raise ValueError(f"no single filter word selects {label!r} first")


MAX_LINE = 256  # TestBot rejects the whole script on a longer line


def _log(text: str) -> str:
    return ("log " + text)[:MAX_LINE - 6]


def _type(lines: List[str], text: str) -> None:
    lines.append(f"type {text}")
    lines.append("key right")  # commit (harmless cursor move)


def open_editor_lines(mod_search: str) -> List[str]:
    """Main menu -> Mods -> search -> first mod -> Edit -> F3 animation editor."""
    out: List[str] = [
        "wait_screen MainMenuScreen 120000",
        "click 244 202",
        "wait_screen ModsScreen 15000",
        "wait 1000",
        "click 555 228",
        "wait 300",
    ]
    # the search may still hold an earlier mod's text when a script visits several mods
    out += ["key right"] * 30 + ["key backspace"] * 30
    _type(out, mod_search)
    out += [
        "wait 800", "click 535 274", "wait 600", "click 1428 843",
        "wait_screen MapMakerScreen 60000", "wait 1500", "key f3",
        "wait_screen AnimatorScreen 15000", "wait 2500",
    ]
    return out


def open_editor_script(mod_search: str) -> str:
    """INI/inbox script that only opens the F3 editor and stops there (for inbox-driven checks)."""
    out = ["# Generated by s2_skill_cli.py: open the F3 animation editor and stay there. Never Accepts.",
           "# KEEP THE GAME WINDOW FOCUSED."]
    out += open_editor_lines(mod_search)
    out += ["log_screen", "snapshot editor_open 1", "log editor open: send checks through the inbox"]
    return "\n".join(out) + "\n"


def build_script(mod_search: Optional[str], checks: Sequence[AnimCheck], *, preview_frames: int = 20,
                 preview_ms: int = 120, navigate: bool = True, leave: bool = True, tag_prefix: str = "ec",
                 prev_search: Optional[str] = None) -> str:
    """navigate/leave=False: an inbox job that starts and ends in the open AnimatorScreen.

    prev_search: the text a previous job left in the animation search (sizes the clearing; unknown ->
    a generous clear). TestBot scripts are capped at 2000 steps, so clearing is sized, not fixed."""
    out: List[str] = [
        "# Generated by s2_skill_cli.py editor-flag-check. Read-only: never presses Accept.",
        "# KEEP THE GAME WINDOW FOCUSED.",
    ]
    if navigate:
        out += open_editor_lines(mod_search or "")
    else:
        out += ["wait_screen AnimatorScreen 10000"]  # aborts (no stray clicks) when the editor is not open
    for ci, check in enumerate(checks):
        tag = f"{tag_prefix}{ci:02d}"
        out += ["", f"# ---- {check.label or check.search} ----", "click 220 570", "wait 400", "click 220 570", "wait 300"]
        # the click puts the cursor where it lands (mid-text): walk to the end, then delete everything
        # (TestBot has no End/Delete key). Too few of either left stale text and an empty list behind.
        n = 70 if prev_search is None else len(prev_search) + 6
        out += ["key right"] * n
        out += ["key backspace"] * (n + 4)
        _type(out, check.search)
        prev_search = check.search
        out += ["wait 1000", f"snapshot {tag}_search 1", f"click {SEARCH_ROW_EDIT[0]} {SEARCH_ROW_EDIT[1] + LIST_ROW * check.row}", "wait 1200",
                f"snapshot {tag}_preview_before {preview_frames} {preview_ms}"]
        for ed in check.edits:
            px, py = particle_icon(ed.particle)
            ptag = f"{tag}_p{ed.particle}"
            out += [f"click {px} {py}", "wait 800", f"snapshot {ptag}_form_before 1"]
            value = ed.current
            # remove highest bit first so the row index of lower ones stays valid
            for bit in sorted(set(ed.clear_bits), reverse=True):
                if not value & (1 << bit):
                    continue
                idx = bin(value & ((1 << bit) - 1)).count("1")
                out += [f"# remove {pf.FLAGS[bit][2]}", f"click {ACTIVE_X} {ACTIVE_Y0 + ROW * idx}", "wait 500"]
                value &= ~(1 << bit)
            for bit in sorted(set(ed.set_bits)):
                if value & (1 << bit):
                    continue
                label = pf.FLAGS[bit][2]
                out += [f"# add {label}", f"click {SETTINGS_INPUT[0]} {SETTINGS_INPUT[1]}", "wait 500"]
                # the field keeps unmatched text across picks and reloads, cursor at the click: clear it
                out += ["key right"] * 40 + ["key backspace"] * 40
                _type(out, filter_word(bit))  # never a space: it picks the highlighted option
                out += ["wait 600", f"click {FIRST_OPTION[0]} {FIRST_OPTION[1]}", "wait 500",
                        "key escape", "wait 400"]  # the dropdown reopens unfiltered: never click to close
                value |= 1 << bit
            if value != ed.current:
                out += [_log(f"{ptag} expected flags {value} = {pf.describe(value, labels=True)}"),
                        f"snapshot {ptag}_form_after 1"]
            else:
                out += [_log(f"{ptag} flags {value} = {pf.describe(value, labels=True)}")]
            out += [f"click {PARTICLE_FORM_CLOSE[0]} {PARTICLE_FORM_CLOSE[1]}", "wait 600"]
        if any(e.set_bits or e.clear_bits for e in check.edits):
            out += [f"snapshot {tag}_preview_after {preview_frames} {preview_ms}"]
    if leave:
        out += ["", "# leave without Accept", "key f4", "wait 1500", "wait_screen MainMenuScreen 30000",
                "mods_errors"]
    out += ["log editor flag check done"]
    return "\n".join(out) + "\n"


def edits_from_animation(anim: Dict, particle: Optional[str], set_flags, clear_flags, toggle_flags=None) -> List[ParticleEdit]:
    edits = []
    add = pf.to_value(set_flags) if set_flags else 0
    rem = pf.to_value(clear_flags) if clear_flags else 0
    tog = pf.to_value(toggle_flags) if toggle_flags else 0
    for n, part in pf.select_particles(anim, particle):
        cur = int(part.get("flags") or 0) | pf.legacy_bits(part)
        s = add | (tog & ~cur)
        c = rem | (tog & cur)
        edits.append(ParticleEdit(n, cur, [b for b in range(len(pf.FLAGS)) if s >> b & 1],
                                  [b for b in range(len(pf.FLAGS)) if c >> b & 1]))
    return edits


MAX_STEPS = 1900  # TestBot limit is 2000 steps / 64 KiB per script


def script_steps(text: str) -> int:
    return sum(1 for ln in text.splitlines() if ln.split("#", 1)[0].strip())


def survey_jobs(mod_search: str, checks: Sequence[AnimCheck], *, preview_frames: int = 12, preview_ms: int = 150,
                first_navigates: bool = True, tag: str = "sv", max_steps: int = MAX_STEPS) -> List[str]:
    """Split a long editor run into inbox jobs under the step/size cap. The first job opens the editor
    (unless first_navigates=False: the editor is already open), the last leaves with F4; the jobs in
    between start with wait_screen AnimatorScreen so a failed predecessor aborts them cleanly."""
    jobs: List[List[AnimCheck]] = []
    cur: List[AnimCheck] = []

    def render(group, idx, last, prev):
        return build_script(mod_search, group, preview_frames=preview_frames, preview_ms=preview_ms,
                            navigate=(idx == 0 and first_navigates), leave=last,
                            tag_prefix=f"{tag}{idx:02d}_", prev_search=prev)

    prev = None
    for c in checks:
        trial = render(cur + [c], len(jobs), True, prev)
        if cur and (script_steps(trial) > max_steps or len(trial.encode()) > 60000):
            jobs.append(cur)
            prev = cur[-1].search
            cur = []
        cur.append(c)
    if cur:
        jobs.append(cur)
    out, prev = [], None
    for i, group in enumerate(jobs):
        text = render(group, i, i == len(jobs) - 1, prev)
        if script_steps(text) > 2000 or len(text.encode()) > 65536:
            raise ValueError(f"job {i} too large even with one animation ({group[0].search})")
        out.append(text)
        prev = group[-1].search
    return out


def _name(path: Path) -> str:
    import json

    try:
        return str(json.loads(path.read_text(encoding="utf-8-sig")).get("name") or "")
    except Exception:
        return ""


def list_row(search: str, anim_file) -> int:
    """Row of `anim_file` in the F3 list filtered by `search`: core_2 animations come first (by numeric
    id: 188 Fire Rain drop impact, 189 ... fall, then the mod's Fire Rain Drop), then the mod's own files
    in file order. Other mods are not counted; the _search snapshot shows the list actually drawn."""
    import re

    anim_file = Path(anim_file)
    q = search.lower()
    core = anim_file.parents[2] / "core_2" / "animations"
    def num(p: Path):
        m = re.match(r"(\d+)", p.stem)
        return (int(m.group(1)) if m else 10**9, p.name)
    row = sum(1 for p in sorted(core.glob("*.json"), key=num) if q in _name(p).lower()) if core.is_dir() else 0
    for p in sorted(anim_file.parent.glob("*.json")):
        if p.name == anim_file.name:
            break
        if q in _name(p).lower():
            row += 1
    return row
