// GPU / CPU light categories.
// Must stay in sync with the shader enum generated by LightShaderGen.
enum class LightType : uint32_t { Directional = 0, Point = 1, Spot = 2, Area = 3 };

struct LightParams {
    std::string id;                    // unique asset identifier
    LightType   type{LightType::Point};// light category
    Vec3        position{0.0f};        // world position (ignored for directional lights)
    Vec3        direction{0.0f, -1.0f, 0.0f}; // spot / directional / area facing direction
    Vec3        color{1.0f};           // RGB radiance (linear space)
    float       intensity{1.0f};       // luminous power (candela / lux depending on engine)
    float       range{10.0f};          // attenuation range (non-directional)
    float       innerAngle{30.0f};     // spot light: inner cone (deg)
    float       outerAngle{45.0f};     // spot light: outer cone (deg)
    Vec2        areaSize{1.0f, 1.0f};  // area light width / height
    bool        volumetric{};          // enable volumetric shafts
    bool        dynamic{};             // participates in runtime animations / movement

    // Hash key for use in caches
    uint64_t hashKey() const {
        ParamHasher h(0x4C49474854ull); // "LIGHT"
        h.str(id);
        h.pod(type);
        h.vec(position);
        h.vec(direction);
        h.vec(color);
        h.pod(intensity);
        h.pod(range);
        h.pod(innerAngle);
        h.pod(outerAngle);
        h.vec(areaSize);
        h.pod(volumetric);
        h.pod(dynamic);
        return h.digest();
    }
};

struct ShadowParams {
    bool  castShadows{true};
    int   resolution{1024};
    int   cascades{1}; // directional lights only
    float bias{0.002f};
    float normalBias{0.005f};

    uint64_t hashKey() const {
        ParamHasher h(0x534841444F57ull); // "SHADOW"
        h.pod(castShadows);
        h.pod(resolution);
        h.pod(cascades);
        h.pod(bias);
        h.pod(normalBias);
        return h.digest();
    }
};

struct CookieParams {
    bool        useCookie{false};
    std::string texturePath; // asset path (relative to the GPUDeviceInterface asset root, or absolute)
    Vec2        uvScale{1.0f, 1.0f};
    Vec2        uvOffset{0.0f, 0.0f};

    uint64_t hashKey() const {
        ParamHasher h(0x434F4F4B4945ull); // "COOKIE"
        h.pod(useCookie);
        h.str(texturePath);
        h.vec(uvScale);
        h.vec(uvOffset);
        return h.digest();
    }
};

struct VolumetricParams {
    float density{0.0f};
    Vec3  scatterColor{1.0f, 1.0f, 1.0f};
    float anisotropy{0.0f}; // Henyey-Greenstein g in [-1, 1]

    uint64_t hashKey() const {
        ParamHasher h(0x564F4C554D45ull); // "VOLUME"
        h.pod(density);
        h.vec(scatterColor);
        h.pod(anisotropy);
        return h.digest();
    }
};

struct FlickerParams {
    enum class Pattern : uint32_t { Sine = 0, Perlin = 1, Random = 2 };

    bool    enabled{false};
    float   frequency{4.0f};
    Vec2    amplitude{0.8f, 1.2f}; // min / max intensity multiplier
    Pattern pattern{Pattern::Perlin};

    uint64_t hashKey() const {
        ParamHasher h(0x464C49434B52ull); // "FLICKR"
        h.pod(enabled);
        h.pod(frequency);
        h.vec(amplitude);
        h.pod(pattern);
        return h.digest();
    }
};

struct LODParams {
    std::vector<float> screenSizes;   // per LOD screen size thresholds (normalized)
    std::vector<int>   shadowRes;     // per LOD shadow resolution
    std::vector<bool>  volumetricOn;  // per LOD volumetric toggle
    std::vector<bool>  cookieOn;      // per LOD cookie toggle

    uint64_t hashKey() const {
        ParamHasher h(0x4C4F44ull); // "LOD"
        h.list(screenSizes);
        h.list(shadowRes);
        h.list(volumetricOn);
        h.list(cookieOn);
        return h.digest();
    }
};

// Convenience helpers --------------------------------------------------------------------------------------------------

inline uint64_t hashCombine(uint64_t a, uint64_t b) {
    const uint64_t pair[2] = {a, b};
    return XXH3_64bits(pair, sizeof(pair));
}

template <typename... Rest>
inline uint64_t hashCombine(uint64_t a, uint64_t b, uint64_t c, Rest... rest) {
    return hashCombine(hashCombine(a, b), c, static_cast<uint64_t>(rest)...);
}

template <typename T>
inline uint64_t hashParams(const T& p) { return p.hashKey(); }

