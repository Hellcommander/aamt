// ---------------------------------------------------------------------------------------------------------------------
// Hashing helper: field-wise hashing (never hashes raw structs, so padding and std::string internals
// cannot make keys non-deterministic).
// ---------------------------------------------------------------------------------------------------------------------
class ParamHasher {
public:
    explicit ParamHasher(uint64_t seed = 0x9E3779B97F4A7C15ull) : m_hash(seed) {}

    void bytes(const void* data, size_t size) { m_hash = XXH3_64bits_withSeed(data, size, m_hash); }

    template <typename T>
    void pod(const T& value) {
        static_assert(std::is_trivially_copyable_v<T>, "pod() requires a trivially copyable type");
        bytes(&value, sizeof(T));
    }

    void str(const std::string& s) {
        pod(s.size());
        if (!s.empty()) bytes(s.data(), s.size());
    }

    void vec(const Vec2& v) { pod(v.x); pod(v.y); }
    void vec(const Vec3& v) { pod(v.x); pod(v.y); pod(v.z); }

    template <typename T>
    void list(const std::vector<T>& v) {
        pod(v.size());
        for (const auto& e : v) {
            const T value = e; // also handles std::vector<bool> proxies
            pod(value);
        }
    }

    uint64_t digest() const { return m_hash; }

private:
    uint64_t m_hash;
};

