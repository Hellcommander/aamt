    /// <summary>
    /// Older dump refreshes used <c>Type.Member(</c> for instance methods, which almost never
    /// appears in mod source (<c>receiver.Member(</c> does). Rewrite those patterns in place
    /// without touching curated notes / autoFixable flags.
    /// </summary>
    public static int HealInstanceMethodSearchPatterns(ObsoleteDump dump)
    {
        var healed = 0;
        foreach (var e in dump.Entries)
        {
            if (!string.Equals(e.Kind, "Method", StringComparison.OrdinalIgnoreCase))
                continue;
            if (string.IsNullOrEmpty(e.Member) || string.IsNullOrEmpty(e.Type))
                continue;
            if (LooksStaticSignature(e.Signature))
                continue;

            var shortType = ShortTypeName(e.Type);
            var legacy = shortType + @"\." + System.Text.RegularExpressions.Regex.Escape(e.Member) + @"\(";
            var preferred = @"\." + System.Text.RegularExpressions.Regex.Escape(e.Member) + @"\(";
            if (string.Equals(e.SearchPattern, legacy, StringComparison.Ordinal) ||
                string.Equals(e.SearchPattern, shortType + "." + e.Member + "(", StringComparison.Ordinal))
            {
                e.SearchPattern = preferred;
                healed++;
            }
            // Also heal the common "Type\.Member\(" form produced by Regex.Escape on Type.
            else if (e.SearchPattern == System.Text.RegularExpressions.Regex.Escape(shortType) + @"\." +
                     System.Text.RegularExpressions.Regex.Escape(e.Member) + @"\(")
            {
                e.SearchPattern = preferred;
                healed++;
            }
        }
        return healed;
    }

    private static bool LooksStaticSignature(string? signature)
    {
        if (string.IsNullOrWhiteSpace(signature)) return false;
        var s = signature.TrimStart();
        return s.StartsWith("static ", StringComparison.Ordinal);
    }

    private static string ShortTypeName(string type)
    {
        var shortType = type.Contains('.') ? type[(type.LastIndexOf('.') + 1)..] : type;
        var tick = shortType.IndexOf('`');
        if (tick >= 0) shortType = shortType[..tick];
        return shortType;
    }

    private static List<ObsoleteEntry> DedupeAdded(List<DiscoveredMember> added)
    {
        var result = new List<ObsoleteEntry>();
        foreach (var group in added.GroupBy(m => (m.Type, m.Member)))
        {
            var members = group.ToList();
            var first = members[0];
            var distinctMessages = members.Select(m => m.ObsoleteMessage?.Trim() ?? "").Distinct().ToList();
            result.Add(new ObsoleteEntry
            {
                Type = first.Type,
                Member = first.Member,
                Kind = first.Kind,
                Signature = members.Count == 1 ? first.Signature : $"{members.Count} overload(s), e.g. {first.Signature}",
                ObsoleteMessage = string.Join(" | ", distinctMessages),
                SearchPattern = DerivePattern(first),
                NeedsManual = true,
                AutoFixable = false,
                Notes = "Auto-added by a dump refresh; unreviewed - verify replacement signature before promoting to a curated rule.",
            });
        }
        return result;
    }

    public static string DerivePattern(DiscoveredMember m)
    {
        // Prefer call-site patterns that match real mod code (obj.the, DidX(, …), not
        // fully-qualified Type.Member which almost never appears in source.
        var member = m.Member;
        var type = m.Type ?? "";

        if (type.Contains("IComponent") && member is "DidX" or "DidXToY" or "DidXToYWithZ"
            or "XDidY" or "XDidYToZ" or "WDidXToYWithZ")
            return $@"\b{System.Text.RegularExpressions.Regex.Escape(member)}\(";

        if (type.EndsWith("Messaging", StringComparison.Ordinal) &&
            member is "XDidY" or "XDidYToZ" or "WDidXToYWithZ")
            return $@"(?:Messaging\.)?{System.Text.RegularExpressions.Regex.Escape(member)}\(";

        if (type.EndsWith("GameObject", StringComparison.Ordinal) &&
            member is "the" or "The" or "a" or "A" or "an" or "An" or "its" or "Its"
            or "itself" or "Itself" or "It" or "it" or "Them" or "them" or "They" or "they"
            or "Their" or "their" or "tis" or "Tis" or "itis" or "Is" or "are")
            // Exclude GameText =subject.The= / =subject.the.name= tokens.
            return $@"\.{System.Text.RegularExpressions.Regex.Escape(member)}\b(?![.=:#])";

        if (type.EndsWith("GameObject", StringComparison.Ordinal) &&
            member is "Does" or "does" or "GetVerb" or "poss" or "Poss")
            return $@"\.{System.Text.RegularExpressions.Regex.Escape(member)}\(";

        // IEventRegistrar.RegisterPartEvent collides with non-obsolete GameObject.RegisterPartEvent.
        if (type.EndsWith("IEventRegistrar", StringComparison.Ordinal) &&
            member is "RegisterPartEvent" or "UnregisterPartEvent")
            return $@"(?i)Registrar\.{System.Text.RegularExpressions.Regex.Escape(member)}\(";

        // Obsolete Register(GameObject) only — not Register(Object, IEventRegistrar) / Registrar.Register(string).
        if ((type.EndsWith(".IPart", StringComparison.Ordinal) || type.EndsWith(".Effect", StringComparison.Ordinal) ||
             type is "XRL.World.IPart" or "XRL.World.Effect") &&
            member is "Register" or "Unregister")
            return $@"(?<![Rr]egistrar)\.{System.Text.RegularExpressions.Regex.Escape(member)}\(\s*[^,\)]+\s*\)";

        // BodyPart.Save is obsolete; bare .Save( matches every serialization wrapper.
        if (type.EndsWith("BodyPart", StringComparison.Ordinal) && member == "Save")
            return @"BodyPart\.Save\(";

        // HistoricEntity/Event.ExpandString vs mod wrappers named ExpandString.
        if (type.EndsWith("HistoricEntity", StringComparison.Ordinal) && member == "ExpandString")
            return @"(?i)(?:HistoricEntity|\bentity)\.ExpandString\(";
        if (type.EndsWith("HistoricEvent", StringComparison.Ordinal) && member == "ExpandString")
            return @"(?i)(?:HistoricEvent|\bevent)\.ExpandString\(";

        if (member is "Capitalize" or "CapitalizeExceptFormatting")
            return $@"\.{System.Text.RegularExpressions.Regex.Escape(member)}\(";

        var shortType = ShortTypeName(type);

        // Instance methods: mods call receiver.Member(, almost never Type.Member(.
        // Signature from FormatMethodSignature prefixes static methods with "static ".
        if (string.Equals(m.Kind, "Method", StringComparison.OrdinalIgnoreCase) &&
            !LooksStaticSignature(m.Signature))
        {
            return $@"\.{System.Text.RegularExpressions.Regex.Escape(member)}\(";
        }

        return m.Kind == "Method"
            ? $@"{System.Text.RegularExpressions.Regex.Escape(shortType)}\.{System.Text.RegularExpressions.Regex.Escape(member)}\("
            : $@"{System.Text.RegularExpressions.Regex.Escape(shortType)}\.{System.Text.RegularExpressions.Regex.Escape(member)}\b";
    }

    /// <summary>Backs up the existing dump file (if present) then writes the merged dump.
    /// Also stamps game FileVersion meta and refreshes <c>data/by-version/{version}/</c>
    /// (dump + curated rules). Returns the backup path, or null if there was nothing to back up.</summary>
    public static string? SaveWithBackup(string dumpPath, string backupDir, ObsoleteDump merged,
        string? dataDir = null, string? managedDir = null)
    {
        string? backupPath = null;
        if (File.Exists(dumpPath))
        {
            backupPath = DumpStore.Backup(dumpPath, backupDir);
        }
        dataDir ??= Path.GetDirectoryName(Path.GetFullPath(dumpPath));
        if (!string.IsNullOrEmpty(dataDir))
        {
            DumpVersionControl.AfterDumpSaved(dataDir, merged, managedDir);
        }
        else
        {
            DumpStore.SaveDump(dumpPath, merged);
        }
        return backupPath;
    }

    /// <summary>
    /// Writes a markdown research report (added / changed / removed) next to other tool reports.
    /// Used by the GUI "Update ApiMigrator" flow so dump refreshes are reviewable later.
    /// </summary>
    public static string WriteResearchReport(RefreshPreview preview, string reportPath, string dumpPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(reportPath));
        if (!string.IsNullOrEmpty(dir))
            Directory.CreateDirectory(dir);

        var sb = new System.Text.StringBuilder();
        sb.AppendLine("# ApiMigrator DLL Research");
        sb.AppendLine();
        sb.AppendLine($"- Captured: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine($"- Dump target: `{dumpPath}`");
        sb.AppendLine($"- Types scanned: {preview.Scan.TypesScanned}");
        sb.AppendLine($"- Obsolete members found: {preview.Scan.Members.Count}");
        sb.AppendLine();

        if (preview.Diff is { } diff)
        {
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.AppendLine($"| Unchanged | Added | Removed | Message changed |");
            sb.AppendLine($"|----------:|------:|--------:|----------------:|");
            sb.AppendLine($"| {diff.UnchangedCount} | {diff.Added.Count} | {diff.Removed.Count} | {diff.MessageChanged.Count} |");
            sb.AppendLine();

            if (diff.Added.Count > 0)
            {
                sb.AppendLine("## Added");
                sb.AppendLine();
                foreach (var m in diff.Added)
                    sb.AppendLine($"- `{m.Type}.{m.Member}` — {m.ObsoleteMessage}");
                sb.AppendLine();
            }

            if (diff.MessageChanged.Count > 0)
            {
                sb.AppendLine("## Message changed");
                sb.AppendLine();
                foreach (var (oldE, newM) in diff.MessageChanged)
                {
                    sb.AppendLine($"- `{oldE.Type}.{oldE.Member}`");
                    sb.AppendLine($"  - was: {oldE.ObsoleteMessage}");
                    sb.AppendLine($"  - now: {newM.ObsoleteMessage}");
                }
                sb.AppendLine();
            }

            if (diff.Removed.Count > 0)
            {
                sb.AppendLine("## Removed (no longer obsolete / gone from Managed)");
                sb.AppendLine();
                foreach (var e in diff.Removed)
                    sb.AppendLine($"- `{e.Type}.{e.Member}` — {e.ObsoleteMessage}");
                sb.AppendLine();
            }
        }
        else
        {
            sb.AppendLine("No prior dump — this refresh creates a new obsolete map.");
            sb.AppendLine();
        }

        if (preview.Scan.Warnings.Count > 0)
        {
            sb.AppendLine("## Scan warnings");
            sb.AppendLine();
            foreach (var w in preview.Scan.Warnings)
                sb.AppendLine($"- {w}");
            sb.AppendLine();
        }

        sb.AppendLine("## What this updates");
        sb.AppendLine();
        sb.AppendLine("Saving the merged dump updates **ApiMigrator** itself: Migrate, CS0618 Resolve, and Obsolete Map all read `obsolete_api_dump.json`. Curated autofix regexes in `curated_rewrite_rules.json` stay hand-maintained — new dump entries are flagged `needsManual` until promoted to a curated rule.");

        File.WriteAllText(reportPath, sb.ToString());
        return reportPath;
    }
}
