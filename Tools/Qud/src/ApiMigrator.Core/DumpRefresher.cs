namespace ApiMigrator.Core;

/// <summary>
/// Shared "research + merge" workflow used by both the CLI (refresh-dump) and the GUI
/// (DLL Research tab), so the two never drift out of sync. Scanning is always read-only
/// against the Managed DLLs; nothing is written until SaveWithBackup is explicitly called.
/// </summary>
public static class DumpRefresher
{
    public sealed class RefreshPreview
    {
        public DllResearcher.ScanResult Scan { get; init; } = null!;
        public DumpDiffResult? Diff { get; init; }
        public ObsoleteDump OldDump { get; init; } = null!;
        public bool HadExistingDump { get; init; }
    }

    /// <summary>Reflects the given DLLs and diffs the result against whatever dump currently
    /// exists at dumpPath (or an empty dump if none exists yet). Nothing is written to disk.</summary>
    public static RefreshPreview Scan(string managedDir, IEnumerable<string> dlls, string dumpPath)
    {
        var scan = DllResearcher.ScanForObsoleteMembers(managedDir, dlls);
        var hadExisting = File.Exists(dumpPath);
        var oldDump = hadExisting ? DumpStore.LoadDump(dumpPath) : new ObsoleteDump { Entries = new() };
        var diff = hadExisting ? DllResearcher.Diff(oldDump, scan.Members) : null;
        return new RefreshPreview { Scan = scan, Diff = diff, OldDump = oldDump, HadExistingDump = hadExisting };
    }

    /// <summary>
    /// Builds the merged dump in-memory (existing curated entries preserved verbatim, new
    /// members appended - deduped per overload group - and single-overload message changes
    /// applied in place). Does not touch disk.
    /// </summary>
    public static ObsoleteDump BuildMerged(RefreshPreview preview, IEnumerable<string> managedDllPaths)
    {
        if (!preview.HadExistingDump || preview.Diff is null)
        {
            return new ObsoleteDump
            {
                Meta = new ObsoleteDumpMeta
                {
                    Description = "Obsolete Caves of Qud (Assembly-CSharp.dll) API -> replacement map. Generated by ApiMigrator refresh-dump.",
                    Source = "Generated via ApiMigrator.Core.DllResearcher (Assembly.LoadFrom reflection over live Managed DLLs).",
                    AssemblySource = string.Join(", ", managedDllPaths),
                    ApiDumpTool = "ApiMigrator refresh-dump",
                    CapturedDate = DateTime.Now.ToString("yyyy-MM-dd"),
                },
                Entries = DedupeAdded(preview.Scan.Members),
            };
        }

        var merged = preview.OldDump;
        foreach (var (oldE, newM) in preview.Diff.MessageChanged)
        {
            oldE.ObsoleteMessage = newM.ObsoleteMessage;
        }
        merged.Entries.AddRange(DedupeAdded(preview.Diff.Added));
        HealInstanceMethodSearchPatterns(merged);
        TightenNoisySearchPatterns(merged);
        merged.Meta ??= new ObsoleteDumpMeta();
        merged.Meta.CapturedDate = DateTime.Now.ToString("yyyy-MM-dd");
        return merged;
    }

    /// <summary>
    /// Re-applies known false-positive-safe pattern tightenings when an entry still has the
    /// naive refresh-default pattern. Never overwrites a hand-customized <c>searchPattern</c>.
    /// </summary>
    public static int TightenNoisySearchPatterns(ObsoleteDump dump)
    {
        var tightened = 0;
        foreach (var e in dump.Entries)
        {
            var key = (e.Type, e.Member);
            if (!NoisyPatternTightenings.TryGetValue(key, out var fix))
                continue;
            // Re-apply when still on the naive pattern, OR when stuck on a known intermediate
            // too-broad tightening (e.g. override GetDescription before we disabled the scan).
            var canTighten = string.Equals(e.SearchPattern, fix.NaivePattern, StringComparison.Ordinal)
                || IntermediateBroadPatterns.TryGetValue(key, out var intermediates)
                   && intermediates.Contains(e.SearchPattern);
            if (!canTighten)
                continue;

            e.SearchPattern = fix.TightPattern;
            if (!string.IsNullOrWhiteSpace(fix.NotesSuffix))
            {
                var suffix = fix.NotesSuffix!;
                if (string.IsNullOrWhiteSpace(e.Notes) ||
                    e.Notes.IndexOf(suffix, StringComparison.OrdinalIgnoreCase) < 0)
                {
                    e.Notes = string.IsNullOrWhiteSpace(e.Notes)
                        ? suffix
                        : e.Notes.TrimEnd() + " " + suffix;
                }
            }
            tightened++;
        }
        return tightened;
    }

    private readonly record struct PatternFix(string NaivePattern, string TightPattern, string? NotesSuffix);

    /// <summary>
    /// Patterns left by earlier tightenings that are still too broad and should be upgraded
    /// to the current <see cref="NoisyPatternTightenings"/> target.
    /// </summary>
    private static readonly Dictionary<(string Type, string Member), HashSet<string>> IntermediateBroadPatterns = new()
    {
        [("XRL.World.Parts.IStingerProperties", "GetDescription")] = new(StringComparer.Ordinal)
        {
            @"(?m)override\s+string\s+GetDescription\s*\(",
        },
        [("XRL.World.Parts.IStingerProperties", "AppendLevelText")] = new(StringComparer.Ordinal)
        {
            @"(?m)override\s+void\s+AppendLevelText\s*\(",
        },
    };

