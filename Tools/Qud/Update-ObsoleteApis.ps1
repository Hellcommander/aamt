function Test-HasUsing {
    param([string]$Content, [string]$Namespace)
    return [regex]::IsMatch($Content, "(?m)^(?:global\s+)?using\s+$([regex]::Escape($Namespace))\s*;")
}

function Add-MissingUsings {
    param([string]$Content, [string[]]$Namespaces)
    $needed = @(
        $Namespaces |
            Where-Object { $_ -and $_.Trim() } |
            Select-Object -Unique |
            Where-Object { -not (Test-HasUsing -Content $Content -Namespace $_) } |
            Sort-Object
    )
    if ($needed.Count -eq 0) {
        return [PSCustomObject]@{ Content = $Content; Inserted = @() }
    }

    $nl = if ($Content -match "`r`n") { "`r`n" } else { "`n" }
    $block = ($needed | ForEach-Object { "using $_;$nl" }) -join ''

    $usingMatches = [regex]::Matches($Content, '(?m)^(?:global\s+)?using\s+[^;]+;\r?\n')
    if ($usingMatches.Count -gt 0) {
        $last = $usingMatches[$usingMatches.Count - 1]
        $insertAt = $last.Index + $last.Length
        $newContent = $Content.Insert($insertAt, $block)
        return [PSCustomObject]@{ Content = $newContent; Inserted = $needed }
    }

    $nsMatch = [regex]::Match($Content, '(?m)^(?:(?:public|internal|file)\s+)?namespace\s')
    if ($nsMatch.Success) {
        $newContent = $Content.Insert($nsMatch.Index, $block + $nl)
        return [PSCustomObject]@{ Content = $newContent; Inserted = $needed }
    }

    return [PSCustomObject]@{ Content = ($block + $nl + $Content); Inserted = $needed }
}

