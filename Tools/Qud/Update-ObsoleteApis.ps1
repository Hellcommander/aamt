function Test-ExcludedPath {
    param([string]$FullPath)
    $normalized = $FullPath -replace '/', '\'
    foreach ($dir in $ExcludeDirs) {
        if ($normalized -match "(?i)\\$([regex]::Escape($dir))(\\|$)") { return $true }
    }
    return $false
}

function Get-TargetFiles {
    param([string[]]$Roots)
    $files = New-Object System.Collections.Generic.List[System.IO.FileInfo]
    foreach ($root in $Roots) {
        if (-not (Test-Path -LiteralPath $root)) {
            Write-Warning "Path not found, skipping: $root"
            continue
        }
        if (Test-Path -LiteralPath $root -PathType Leaf) {
            $item = Get-Item -LiteralPath $root
            if ($ScanExtensions -contains $item.Extension.ToLowerInvariant() -and
                -not (Test-ExcludedPath $item.FullName)) {
                if (-not $Mod -or $item.FullName -like "*$Mod*") { $files.Add($item) }
            }
            continue
        }
        $rootFiles = Get-ChildItem -LiteralPath $root -Recurse -File -ErrorAction SilentlyContinue |
            Where-Object {
                $ScanExtensions -contains $_.Extension.ToLowerInvariant() -and
                -not (Test-ExcludedPath $_.FullName)
            }
        if ($Mod) {
            $rootFiles = $rootFiles | Where-Object { $_.FullName -match "(?i)\\$([regex]::Escape($Mod))(\\|_[^\\]*\\)" -or $_.FullName -like "*\$Mod\*" -or $_.FullName -like "*$Mod*" }
        }
        foreach ($f in $rootFiles) { $files.Add($f) }
    }
    return $files
}

function Get-ManifestTargetFiles {
    param([string[]]$Roots)
    $names = @('manifest.json', 'Manifest.json', 'config.json', 'Config.json')
    $files = New-Object System.Collections.Generic.List[System.IO.FileInfo]
    foreach ($root in $Roots) {
        if (-not (Test-Path $root)) { continue }
        $rootFiles = Get-ChildItem -LiteralPath $root -Recurse -File -ErrorAction SilentlyContinue |
            Where-Object {
                ($names -contains $_.Name) -and
                -not (Test-ExcludedPath $_.FullName)
            }
        if ($Mod) {
            $rootFiles = $rootFiles | Where-Object { $_.FullName -match "(?i)\\$([regex]::Escape($Mod))(\\|_[^\\]*\\)" -or $_.FullName -like "*\$Mod\*" -or $_.FullName -like "*$Mod*" }
        }
        foreach ($f in $rootFiles) { $files.Add($f) }
    }
    return $files
}

