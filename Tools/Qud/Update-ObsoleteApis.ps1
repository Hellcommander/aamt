function Remove-NullableRefAnnotations {
    <#
    .SYNOPSIS
      Strip #nullable directives and reference-type Type? annotations (CoQ CS8632).
      Keeps ?., ??, ternary, value-type nullables (int?, bool?, DialogResult?, …),
      file-local enums, struct/Enum-constrained type params (TEnum?), and strips List<T>? / T[]?.
    #>
    param([string]$Content)
    if ([string]::IsNullOrEmpty($Content)) {
        return [PSCustomObject]@{ Content = $Content; EditCount = 0 }
    }

    $script:NullableEditCount = 0
    $working = [regex]::Replace($Content, '(?m)^[ \t]*#nullable[ \t]+(?:enable|disable|restore)[ \t]*\r?\n?', {
        $script:NullableEditCount++
        ''
    })

    $preserve = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    foreach ($v in @(
        'bool','byte','sbyte','short','ushort','int','uint','long','ulong','float','double','decimal','char','nint','nuint',
        'Boolean','Byte','SByte','Int16','UInt16','Int32','UInt32','Int64','UInt64','Single','Double','Decimal','Char',
        'DialogResult','DateTime','DateTimeOffset','TimeSpan','Guid','IntPtr','UIntPtr','Half','Rune','Index','Range',
        'DayOfWeek','ConsoleKey','ConsoleModifiers','KeyCode','Color','Color32','Vector2','Vector3','Vector4','Quaternion',
        'Rect','RectInt','Bounds','BoundsInt','Ray','Ray2D','Plane','Matrix4x4','Vector2Int','Vector3Int','LayerMask','Hash128'
    )) { [void]$preserve.Add($v) }

    foreach ($m in [regex]::Matches($Content, '\benum\s+(?<name>[A-Za-z_][\w]*)\b')) {
        [void]$preserve.Add($m.Groups['name'].Value)
    }
    foreach ($m in [regex]::Matches($Content, '\bwhere\s+(?<name>[A-Za-z_][\w]*)\s*:\s*(?:struct\b|Enum\b|System\.Enum\b)')) {
        [void]$preserve.Add($m.Groups['name'].Value)
    }

    $working = [regex]::Replace($working,
        '(?<![.\w])(?<type>[A-Za-z_][\w]*(?:\.[A-Za-z_][\w]*)*)\?(?=\s*(?:[A-Za-z_>\],\)=;\{\[]|/\*|$))',
        {
            param($m)
            $typeName = $m.Groups['type'].Value
            $simple = $typeName
            $dot = $typeName.LastIndexOf('.')
            if ($dot -ge 0) { $simple = $typeName.Substring($dot + 1) }
            if ($preserve.Contains($simple) -or $preserve.Contains($typeName)) {
                return $m.Value
            }
            $script:NullableEditCount++
            return $typeName
        })

    $working = [regex]::Replace($working,
        '(?<=[\]\)>])\?(?=\s*(?:[A-Za-z_>\],\)=;\{\[]|/\*|$))',
        {
            $script:NullableEditCount++
            ''
        })

    return [PSCustomObject]@{ Content = $working; EditCount = $script:NullableEditCount }
}

# Mirrors ApiMigrator.Core.CountMethodGroupFixer — CS0019 .Count method-group fixes/flags.
# Override preference hits: Find-OverridePreferenceHits (mirrors OverridePreferenceScanner).
$script:LinqChainMethods = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
@(
    'Where','Select','SelectMany','OfType','Cast',
    'Concat','Union','Intersect','Except','Zip','Join','GroupJoin',
    'Skip','Take','SkipWhile','TakeWhile','Distinct',
    'OrderBy','OrderByDescending','ThenBy','ThenByDescending',
    'GroupBy','Reverse','AsEnumerable','AsQueryable','DefaultIfEmpty',
    'Append','Prepend'
) | ForEach-Object { [void]$script:LinqChainMethods.Add($_) }
$script:LinqMaterializers = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
@('ToList','ToArray','ToHashSet','ToDictionary','ToLookup') | ForEach-Object { [void]$script:LinqMaterializers.Add($_) }

function Test-IsIdentChar {
    param([char]$c)
    return [char]::IsLetterOrDigit($c) -or $c -eq [char]'_'
}

function Test-IsLinqChainCount {
    param([string]$Content, [int]$CountDotIndex)
    if ($CountDotIndex -le 0 -or $CountDotIndex -ge $Content.Length -or $Content[$CountDotIndex] -ne '.') { return $false }
    $i = $CountDotIndex - 1
    while ($i -ge 0 -and [char]::IsWhiteSpace($Content[$i])) { $i-- }
    if ($i -lt 0 -or $Content[$i] -ne ')') { return $false }

    $depth = 0
    for (; $i -ge 0; $i--) {
        $c = $Content[$i]
        if ($c -eq ')') { $depth++; continue }
        if ($c -eq '(') {
            $depth--
            if ($depth -eq 0) { break }
            continue
        }
    }
    if ($i -lt 0 -or $Content[$i] -ne '(' -or $depth -ne 0) { return $false }

    $beforeCall = $i - 1
    while ($beforeCall -ge 0 -and [char]::IsWhiteSpace($Content[$beforeCall])) { $beforeCall-- }

    if ($beforeCall -ge 0 -and $Content[$beforeCall] -eq '>') {
        $gDepth = 0
        for (; $beforeCall -ge 0; $beforeCall--) {
            $c = $Content[$beforeCall]
            if ($c -eq '>') { $gDepth++; continue }
            if ($c -eq '<') {
                $gDepth--
                if ($gDepth -eq 0) { $beforeCall--; break }
            }
        }
        while ($beforeCall -ge 0 -and [char]::IsWhiteSpace($Content[$beforeCall])) { $beforeCall-- }
    }

    $methodEnd = $beforeCall
    if ($methodEnd -lt 0 -or -not (Test-IsIdentChar -c $Content[$methodEnd])) { return $false }
    while ($methodEnd -ge 0 -and (Test-IsIdentChar -c $Content[$methodEnd])) { $methodEnd-- }
    $methodStart = $methodEnd + 1
    $method = $Content.Substring($methodStart, $beforeCall - $methodStart + 1)

    if ($script:LinqMaterializers.Contains($method)) { return $false }
    if (-not $script:LinqChainMethods.Contains($method)) { return $false }
    return $true
}

function Get-ReceiverNameBeforeCount {
    param([string]$Content, [int]$CountDotIndex)
    $i = $CountDotIndex - 1
    while ($i -ge 0 -and [char]::IsWhiteSpace($Content[$i])) { $i-- }
    if ($i -ge 0 -and $Content[$i] -eq '?') { $i-- }
    while ($i -ge 0 -and [char]::IsWhiteSpace($Content[$i])) { $i-- }
    if ($i -lt 0 -or -not (Test-IsIdentChar -c $Content[$i])) { return $null }
    $end = $i
    while ($i -ge 0 -and (Test-IsIdentChar -c $Content[$i])) { $i-- }
    return $Content.Substring($i + 1, $end - $i)
}

function Get-EnumerableTypedNames {
    param([string]$Content)
    $names = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    $re = [regex]::new('\b(?:IEnumerable|IQueryable|IOrderedEnumerable|IOrderedQueryable)\s*<(?:[^<>]|<[^<>]*>)*>\s+(?<name>[A-Za-z_]\w*)\b')
    foreach ($m in $re.Matches($Content)) {
        if (Test-InsideLineOrBlockComment -Content $Content -Index $m.Index) { continue }
        if (Test-InsideStringLiteralSimple -Content $Content -Index $m.Index) { continue }
        $name = $m.Groups['name'].Value
        $afterName = $m.Index + $m.Length
        while ($afterName -lt $Content.Length -and [char]::IsWhiteSpace($Content[$afterName])) { $afterName++ }
        if ($afterName -lt $Content.Length -and $Content[$afterName] -eq '(') { continue }
        [void]$names.Add($name)
    }
    # Unary comma: keep HashSet as one object (empty must not unwrap to $null).
    return , $names
}

function Repair-CountMethodGroups {
    <#
    .SYNOPSIS
      High-confidence CS0019 fixes: LINQ-chain .Count OP → .Count(); IEnumerable-typed name.Count → .Count().
      Leaves List/Dictionary/ToList().Count property uses alone.
    #>
    param([string]$Content)
    if ([string]::IsNullOrEmpty($Content)) {
        return [PSCustomObject]@{ Content = $Content; EditCount = 0 }
    }

    $enumerableNames = Get-EnumerableTypedNames -Content $Content
    $countCompare = [regex]::new('\.Count(?!\s*\()(?=\s*(?:==|!=|<=|>=|<|>))')
    $matches = $countCompare.Matches($Content)
    if ($matches.Count -eq 0) {
        return [PSCustomObject]@{ Content = $Content; EditCount = 0 }
    }

    $sb = [System.Text.StringBuilder]::new($Content)
    $edits = 0
    for ($i = $matches.Count - 1; $i -ge 0; $i--) {
        $m = $matches[$i]
        if (Test-InsideLineOrBlockComment -Content $Content -Index $m.Index) { continue }
        if (Test-InsideStringLiteralSimple -Content $Content -Index $m.Index) { continue }

        $fix = $false
        if (Test-IsLinqChainCount -Content $Content -CountDotIndex $m.Index) {
            $fix = $true
        }
        else {
            $recv = Get-ReceiverNameBeforeCount -Content $Content -CountDotIndex $m.Index
            if ($recv -and $null -ne $enumerableNames -and $enumerableNames.Contains($recv)) { $fix = $true }
        }
        if (-not $fix) { continue }

        [void]$sb.Insert($m.Index + $m.Length, '()')
        $edits++
    }
    return [PSCustomObject]@{ Content = $sb.ToString(); EditCount = $edits }
}

function Find-CountMethodGroupHits {
    <#
    .SYNOPSIS
      Flag leftover LINQ-chain .Count compares and ?? Enumerable.Empty<(...)> tuple CS0019 notes.
    #>
    param([string]$Content)
    $hits = New-Object System.Collections.Generic.List[object]
    if ([string]::IsNullOrEmpty($Content)) { return $hits }

    $countCompare = [regex]::new('\.Count(?!\s*\()(?=\s*(?:==|!=|<=|>=|<|>))')
    foreach ($m in $countCompare.Matches($Content)) {
        if (Test-InsideLineOrBlockComment -Content $Content -Index $m.Index) { continue }
        if (Test-InsideStringLiteralSimple -Content $Content -Index $m.Index) { continue }
        if (Test-IsLinqChainCount -Content $Content -CountDotIndex $m.Index) {
            $hits.Add([PSCustomObject]@{
                Line    = Get-LineNumberFromIndex -Text $Content -Index $m.Index
                Member  = 'CS0019.CountMethodGroup'
                Message = 'CS0019 method-group Count — use .Count() or .Count property'
                Manual  = $true
                Text    = Get-LineText -Text $Content -Index $m.Index
            })
        }
    }

    $tupleEmpty = [regex]::new('\?\?\s*Enumerable\.Empty\s*<\s*\(')
    foreach ($m in $tupleEmpty.Matches($Content)) {
        if (Test-InsideLineOrBlockComment -Content $Content -Index $m.Index) { continue }
        if (Test-InsideStringLiteralSimple -Content $Content -Index $m.Index) { continue }
        $hits.Add([PSCustomObject]@{
            Line    = Get-LineNumberFromIndex -Text $Content -Index $m.Index
            Member  = 'CS0019.TupleEmptyCoalesce'
            Message = 'CS0019 possible incompatible ?? with Enumerable.Empty<(...)> — named vs unnamed tuple element names often differ; align tuple types by hand'
            Manual  = $true
            Text    = Get-LineText -Text $Content -Index $m.Index
        })
    }
    return $hits
}

