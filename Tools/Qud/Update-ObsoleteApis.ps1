function Repair-BlueprintTypeNamespaces {
    <#
    .SYNOPSIS
      IPart/Mutation/ObjectBuilder classes must live in XRL.World.Parts(.Mutation) /
      ObjectBuilders so ObjectBlueprintLoader ResolveType finds them. Mod-scoped.
    #>
    param([System.Collections.Generic.List[System.IO.FileInfo]]$CsFiles)
    [void](Ensure-ApiMigratorCoreDll)
    $workingMap = @{}
    $fixMap = @{}  # path -> list of {Rule,Count}
    if ($null -eq $CsFiles -or $CsFiles.Count -eq 0) {
        return [PSCustomObject]@{ Working = $workingMap; Fixes = $fixMap }
    }

    $byMod = $CsFiles | Group-Object {
        [ApiMigrator.Core.FileScanner]::GetModRoot($_.FullName)
    }

    foreach ($grp in $byMod) {
        $map = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::OrdinalIgnoreCase)
        foreach ($f in $grp.Group) {
            $text = Get-Content -Raw -LiteralPath $f.FullName -ErrorAction SilentlyContinue
            if ($null -eq $text) { continue }
            $map[$f.FullName] = $text
            # Seed every .cs file — sidecar fixers (Liquids.xml / InventoryActions / Statistics)
            # must see untouched files, not only ones BlueprintTypeNamespaceFixer rewrote.
            if (-not $workingMap.ContainsKey($f.FullName)) {
                $workingMap[$f.FullName] = $text
            }
        }
        if ($map.Count -eq 0) { continue }

        $result = [ApiMigrator.Core.BlueprintTypeNamespaceFixer]::FixMod($map)
        foreach ($kv in $result.UpdatedContents.GetEnumerator()) {
            $workingMap[$kv.Key] = $kv.Value
        }
        foreach ($pair in $result.Fixes) {
            $path = $pair.Item1
            $fix = $pair.Item2
            if (-not $fixMap.ContainsKey($path)) {
                $fixMap[$path] = New-Object System.Collections.Generic.List[object]
            }
            $fixMap[$path].Add([PSCustomObject]@{ Rule = $fix.RuleName; Count = $fix.Count })
        }

        # Refresh map with namespace-fixed content for FriendOrFoe pass
        $fofMap = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::OrdinalIgnoreCase)
        foreach ($f in $grp.Group) {
            if ($workingMap.ContainsKey($f.FullName)) {
                $fofMap[$f.FullName] = $workingMap[$f.FullName]
            }
            elseif ($map.ContainsKey($f.FullName)) {
                $fofMap[$f.FullName] = $map[$f.FullName]
            }
        }
        $fof = [ApiMigrator.Core.FriendOrFoeSpiceFixer]::FixMod($grp.Name, $fofMap)
        foreach ($kv in $fof.UpdatedContents.GetEnumerator()) {
            $workingMap[$kv.Key] = $kv.Value
        }
        foreach ($pair in $fof.Fixes) {
            $path = $pair.Item1
            $fix = $pair.Item2
            if ($fof.SpiceFiles.ContainsKey($path)) { continue }
            if (-not $fixMap.ContainsKey($path)) {
                $fixMap[$path] = New-Object System.Collections.Generic.List[object]
            }
            $fixMap[$path].Add([PSCustomObject]@{ Rule = $fix.RuleName; Count = $fix.Count })
        }
        foreach ($kv in $fof.SpiceFiles.GetEnumerator()) {
            $spicePath = $kv.Key
            $spiceContent = $kv.Value
            $workingMap[$spicePath] = $spiceContent
            if (-not $fixMap.ContainsKey($spicePath)) {
                $fixMap[$spicePath] = New-Object System.Collections.Generic.List[object]
            }
            $fixMap[$spicePath].Add([PSCustomObject]@{
                Rule  = [ApiMigrator.Core.FriendOrFoeSpiceFixer]::FixRuleName + ' (HistorySpice.json)'
                Count = 1
            })
            Write-Host "FriendOrFoe spice → $spicePath" -ForegroundColor DarkCyan
        }

        function Apply-SidecarFixer([string]$Label, $FixerResult) {
            foreach ($kv in $FixerResult.UpdatedContents.GetEnumerator()) {
                $workingMap[$kv.Key] = $kv.Value
            }
            foreach ($pair in $FixerResult.Fixes) {
                $path = $pair.Item1
                $fix = $pair.Item2
                if ($FixerResult.SidecarFiles.ContainsKey($path)) { continue }
                if (-not $fixMap.ContainsKey($path)) {
                    $fixMap[$path] = New-Object System.Collections.Generic.List[object]
                }
                $fixMap[$path].Add([PSCustomObject]@{ Rule = $fix.RuleName; Count = $fix.Count })
            }
            foreach ($kv in $FixerResult.SidecarFiles.GetEnumerator()) {
                $sidePath = $kv.Key
                $sideContent = $kv.Value
                $workingMap[$sidePath] = $sideContent
                if (-not $fixMap.ContainsKey($sidePath)) {
                    $fixMap[$sidePath] = New-Object System.Collections.Generic.List[object]
                }
                $fixMap[$sidePath].Add([PSCustomObject]@{
                    Rule  = $Label
                    Count = 1
                })
                Write-Host "$Label → $sidePath" -ForegroundColor DarkCyan
            }
        }

        function New-CsMap {
            $m = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::OrdinalIgnoreCase)
            foreach ($f in $grp.Group) {
                if ($workingMap.ContainsKey($f.FullName)) { $m[$f.FullName] = $workingMap[$f.FullName] }
                elseif ($map.ContainsKey($f.FullName)) { $m[$f.FullName] = $map[$f.FullName] }
            }
            $xml = Join-Path $grp.Name 'Liquids.xml'
            if ($workingMap.ContainsKey($xml)) { $m[$xml] = $workingMap[$xml] }
            elseif (Test-Path -LiteralPath $xml) { $m[$xml] = Get-Content -Raw -LiteralPath $xml }
            return $m
        }
        Apply-SidecarFixer 'InventoryActions.xml' ([ApiMigrator.Core.InventoryActionsXmlFixer]::FixMod($grp.Name, (New-CsMap)))
        Apply-SidecarFixer 'Statistics.xml' ([ApiMigrator.Core.StatisticCtorFixer]::FixMod($grp.Name, (New-CsMap)))
        Apply-SidecarFixer 'Liquids.xml' ([ApiMigrator.Core.LiquidCsToXmlFixer]::FixMod($grp.Name, (New-CsMap)))
        Apply-SidecarFixer 'Liquids.xml (OnDrink part)' ([ApiMigrator.Core.LiquidDrankToPartFixer]::FixMod($grp.Name, (New-CsMap)))
    }

    return [PSCustomObject]@{ Working = $workingMap; Fixes = $fixMap }
}

