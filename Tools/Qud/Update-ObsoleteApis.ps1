            Rule  = [ApiMigrator.Core.FinalRenderOverrideFixer]::FixRuleName
            Count = [int]$fr.Item2
        })
    }

    $dyn = [ApiMigrator.Core.HarmonyDynamicPatchFixer]::Fix($working)
    $working = $dyn.Item1
    if ($dyn.Item2 -gt 0) {
        $fixList.Add([PSCustomObject]@{
            Rule  = [ApiMigrator.Core.HarmonyDynamicPatchFixer]::FixRuleName
            Count = [int]$dyn.Item2
        })
    }

    $harmonyParam = [ApiMigrator.Core.HarmonyPatchParameterFixer]::Fix($working)
    $working = $harmonyParam.Item1
    if ($harmonyParam.Item2 -gt 0) {
        $fixList.Add([PSCustomObject]@{
            Rule  = [ApiMigrator.Core.HarmonyPatchParameterFixer]::FixRuleName
            Count = [int]$harmonyParam.Item2
        })
    }

    $sif = [ApiMigrator.Core.RemovedGameApiFixer]::Fix($working)
    $working = $sif.Item1
    if ($sif.Item2 -gt 0) {
        $fixList.Add([PSCustomObject]@{
            Rule  = [ApiMigrator.Core.RemovedGameApiFixer]::FixRuleName
            Count = [int]$sif.Item2
        })
    }

    return [PSCustomObject]@{ Content = $working; Fixes = $fixList }
}

function Get-ManualAdvice {
    <#
    .SYNOPSIS
      Actionable manual-fix guidance (never suggests [Obsolete]). Mirrors ManualAdvice.ForMember.
    #>
    param([string]$Member, [string]$Message, [string]$Code = '')
    [void](Ensure-ApiMigratorCoreDll)
    return [ApiMigrator.Core.ManualAdvice]::ForMember(
        $(if ($null -eq $Member) { '' } else { $Member }),
        $(if ($null -eq $Message) { '' } else { $Message }),
        $(if ($null -eq $Code) { '' } else { $Code }))
}

$TargetFiles = @(Get-TargetFiles -Roots $Path)
$ManifestFiles = @(Get-ManifestTargetFiles -Roots $Path)
Write-Host "Found $($TargetFiles.Count) candidate .cs/.xml files to scan." -ForegroundColor Cyan
Write-Host "Found $($ManifestFiles.Count) manifest.json/config.json files to scan." -ForegroundColor Cyan

$CsTargets = New-Object System.Collections.Generic.List[System.IO.FileInfo]
foreach ($f in $TargetFiles) {
    if ($f.Extension -eq '.cs') { [void]$CsTargets.Add($f) }
}
$NsPass = Repair-BlueprintTypeNamespaces -CsFiles $CsTargets
if ($NsPass.Working.Count -gt 0) {
    Write-Host "Blueprint-type namespace fixes prepared for $($NsPass.Working.Count) file(s)." -ForegroundColor DarkCyan
}

# ---------------------------------------------------------------------------
# 5. Process each file: apply curated rules, then scan what's left via the dump
# ---------------------------------------------------------------------------

$FileResults = New-Object System.Collections.Generic.List[object]
$TotalAutoFixes = 0
$TotalRemainingHits = 0
$fileIndex = 0
$fileTotal = $TargetFiles.Count

foreach ($file in $TargetFiles) {
    $fileIndex++
    if ($fileIndex -eq 1 -or ($fileIndex % 25) -eq 0 -or $fileIndex -eq $fileTotal) {
        Write-Host "Scanning $fileIndex/$fileTotal`: $($file.Name)" -ForegroundColor DarkGray
    }

    $original = Get-Content -Raw -LiteralPath $file.FullName -ErrorAction SilentlyContinue
    if ($null -eq $original) { continue }

    $working = $original
    $appliedFixes = New-Object System.Collections.Generic.List[object]
    if ($NsPass.Working.ContainsKey($file.FullName)) {
        $working = $NsPass.Working[$file.FullName]
    }
    if ($NsPass.Fixes.ContainsKey($file.FullName)) {
        foreach ($f in $NsPass.Fixes[$file.FullName]) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.Rule; Count = $f.Count })
        }
    }
    $pendingUsings = New-Object 'System.Collections.Generic.HashSet[string]'
    $isCs = $file.Extension -eq '.cs'

    foreach ($rule in $CuratedRules) {
        if ($rule.RequiresSubstring -and ($working.IndexOf([string]$rule.RequiresSubstring, [StringComparison]::Ordinal) -lt 0)) {
            continue
        }
        try {
            $matches = $rule.Regex.Matches($working)
        }
        catch [System.Text.RegularExpressions.RegexMatchTimeoutException] {
            Write-Warning "$($file.Name): regex timeout on curated rule '$($rule.Name)' (skipped)"
            continue
        }
        if ($matches.Count -gt 0) {
            $appliedFixes.Add([PSCustomObject]@{
                Rule  = $rule.Name
                Count = $matches.Count
            })
            try {
                $working = $rule.Regex.Replace($working, $rule.Replacement)
            }
            catch [System.Text.RegularExpressions.RegexMatchTimeoutException] {
                Write-Warning "$($file.Name): regex timeout replacing curated rule '$($rule.Name)' (skipped)"
                continue
            }
            if ($isCs) {
                foreach ($u in $rule.EnsureUsings) {
                    if ($u) { [void]$pendingUsings.Add([string]$u) }
                }
            }
        }
    }

    if ($isCs) {
        foreach ($post in $PostEnsureUsings) {
            if ($post.IfRegex.IsMatch($working)) {
                foreach ($u in $post.Usings) {
                    if ($u) { [void]$pendingUsings.Add([string]$u) }
                }
            }
        }

        if ($pendingUsings.Count -gt 0) {
            $usingResult = Add-MissingUsings -Content $working -Namespaces @($pendingUsings)
            $working = $usingResult.Content
            if ($usingResult.Inserted.Count -gt 0) {
                $appliedFixes.Add([PSCustomObject]@{
                    Rule  = 'ensure using: ' + ($usingResult.Inserted -join ', ')
                    Count = $usingResult.Inserted.Count
                })
            }
        }

        $nullableResult = Remove-NullableRefAnnotations -Content $working
        if ($nullableResult.EditCount -gt 0) {
            $working = $nullableResult.Content
            $appliedFixes.Add([PSCustomObject]@{
                Rule  = 'strip nullable-ref annotations (#nullable / Type?)'
                Count = $nullableResult.EditCount
            })
        }

        $countResult = Repair-CountMethodGroups -Content $working
        if ($countResult.EditCount -gt 0) {
            $working = $countResult.Content
            $appliedFixes.Add([PSCustomObject]@{
                Rule  = 'Count method-group -> Count() (LINQ / IEnumerable)'
                Count = $countResult.EditCount
            })
        }

        # ShowOptionList→PickOption + simple Register last-resort (ApiMigrator.Core)
        $progResult = Repair-ProgrammaticCsFixes -Content $working
        $working = $progResult.Content
        foreach ($f in $progResult.Fixes) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.Rule; Count = $f.Count })
        }
    }
    elseif ($file.Extension -eq '.xml') {
        [void](Ensure-ApiMigratorCoreDll)
        $closed = [ApiMigrator.Core.XmlUnclosedElementFixer]::Fix($working)
        $working = $closed.Item1
        foreach ($f in $closed.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $inv = [ApiMigrator.Core.ObjectBlueprintXmlFixer]::Fix($working)
        $working = $inv.Item1
        foreach ($f in $inv.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $worlds = [ApiMigrator.Core.WorldsXmlFixer]::Fix($working)
        $working = $worlds.Item1
        foreach ($f in $worlds.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $factions = [ApiMigrator.Core.FactionsXmlFixer]::Fix($working)
        $working = $factions.Item1
        foreach ($f in $factions.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $popXml = [ApiMigrator.Core.PopulationXmlFixer]::Fix($working)
        $working = $popXml.Item1
        foreach ($f in $popXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $liquidXml = [ApiMigrator.Core.LiquidXmlFixer]::Fix($working)
        $working = $liquidXml.Item1
        foreach ($f in $liquidXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $mutXml = [ApiMigrator.Core.MutationsXmlFixer]::Fix($working)
        $working = $mutXml.Item1
        foreach ($f in $mutXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $namingXml = [ApiMigrator.Core.NamingXmlFixer]::Fix($working)
        $working = $namingXml.Item1
        foreach ($f in $namingXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $genoXml = [ApiMigrator.Core.GenotypesXmlFixer]::Fix($working)
        $working = $genoXml.Item1
        foreach ($f in $genoXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $subXml = [ApiMigrator.Core.SubtypesXmlFixer]::Fix($working)
        $working = $subXml.Item1
        foreach ($f in $subXml.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
        $enc = [ApiMigrator.Core.XmlUtf8EncodingFixer]::Ensure($working)
        $working = $enc.Item1
        foreach ($f in $enc.Item2) {
            $appliedFixes.Add([PSCustomObject]@{ Rule = $f.RuleName; Count = $f.Count })
        }
    }

    # Scan the POST-fix content for anything the dump says is still obsolete.
    $remainingHits = New-Object System.Collections.Generic.List[object]
    foreach ($dr in $DumpRegexes) {
        if ($dr.Needle -and ($working.IndexOf([string]$dr.Needle, [StringComparison]::Ordinal) -lt 0)) {
            continue
        }
        try {
            $dumpMatches = $dr.Regex.Matches($working)
        }
        catch [System.Text.RegularExpressions.RegexMatchTimeoutException] {
            Write-Warning "$($file.Name): regex timeout scanning dump '$($dr.Entry.type).$($dr.Entry.member)' (skipped)"
            continue
        }
        foreach ($m in $dumpMatches) {
            if (-not (Test-ShouldReportHit -Entry $dr.Entry -Content $working -Match $m)) { continue }
            $member = "$($dr.Entry.type).$($dr.Entry.member)"
            $msg = $dr.Entry.obsoleteMessage
            $remainingHits.Add([PSCustomObject]@{
                Line    = Get-LineNumberFromIndex -Text $working -Index $m.Index
                Member  = $member
                Message = $msg
                Advice  = Get-ManualAdvice -Member $member -Message $msg -Code (Get-LineText -Text $working -Index $m.Index)
                Manual  = [bool]$dr.Entry.needsManual
                Text    = Get-LineText -Text $working -Index $m.Index
            })
        }
    }
    if ($isCs) {
        foreach ($h in (Find-CountMethodGroupHits -Content $working)) {
            if (-not $h.PSObject.Properties['Advice']) {
                $h | Add-Member -NotePropertyName Advice -NotePropertyValue (Get-ManualAdvice -Member $h.Member -Message $h.Message -Code $h.Text) -Force
            }
            $remainingHits.Add($h)
        }
        foreach ($h in (Find-OverridePreferenceHits -Content $working)) {
            $remainingHits.Add($h)
        }
        [void](Ensure-ApiMigratorCoreDll)
        foreach ($h in [ApiMigrator.Core.LiquidXmlAdviceScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
        foreach ($h in [ApiMigrator.Core.TextBuilderHalfMigrationScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
        foreach ($h in [ApiMigrator.Core.RemovedGameApiFixer]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
    }
    else {
        # Worlds.xml + Liquids.xml report-only; also runs after WorldsXmlFixer / LiquidXmlFixer
        [void](Ensure-ApiMigratorCoreDll)
        foreach ($h in [ApiMigrator.Core.WorldsXmlAdviceScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
        foreach ($h in [ApiMigrator.Core.LiquidXmlRenderAdviceScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
        foreach ($h in [ApiMigrator.Core.FactionsXmlAdviceScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
        foreach ($h in [ApiMigrator.Core.PopulationXmlAdviceScanner]::Scan($working)) {
            $remainingHits.Add([PSCustomObject]@{
                Line    = $h.Line
                Member  = $h.Member
                Message = $h.Message
                Advice  = $h.Advice
                Manual  = $true
                Text    = $h.Text
            })
        }
    }
    $sortedHits = New-Object System.Collections.Generic.List[object]
    foreach ($h in ($remainingHits | Sort-Object Line)) { $sortedHits.Add($h) }
    $remainingHits = $sortedHits

    $changed = ($working -ne $original)

    if ($changed -or $remainingHits.Count -gt 0) {
        $FileResults.Add([PSCustomObject]@{
            File          = $file.FullName
            Changed       = $changed
            AppliedFixes  = $appliedFixes
            RemainingHits = $remainingHits
            NewContent    = $working
        })
        if ($appliedFixes.Count -gt 0) {
            $TotalAutoFixes += ($appliedFixes | Measure-Object -Property Count -Sum).Sum
        }
        $TotalRemainingHits += $remainingHits.Count
    }

    if ($changed -and $Apply) {
        if (-not $NoBackup) {
            $bak = "$($file.FullName).bak"
            if (-not (Test-Path $bak)) {
                Copy-Item -LiteralPath $file.FullName -Destination $bak -Force
            }
        }
        Set-Content -LiteralPath $file.FullName -Value $working -NoNewline:$false -Encoding UTF8
    }
}

# ---------------------------------------------------------------------------
# 5a. FriendOrFoe HistorySpice.json (created by mod-scoped pre-pass; not in .cs/.xml scan)
# ---------------------------------------------------------------------------

foreach ($spicePath in @($NsPass.Working.Keys)) {
    if ($spicePath -notmatch '(?i)[\\/]HistorySpice\.json$') { continue }
    $spiceContent = $NsPass.Working[$spicePath]
    $originalSpice = if (Test-Path -LiteralPath $spicePath) {
        Get-Content -Raw -LiteralPath $spicePath -ErrorAction SilentlyContinue
    } else { '' }
    $changedSpice = ($spiceContent -ne $originalSpice)
    if (-not $changedSpice) { continue }

    $spiceFixes = New-Object System.Collections.Generic.List[object]
    if ($NsPass.Fixes.ContainsKey($spicePath)) {
        foreach ($f in $NsPass.Fixes[$spicePath]) {
            $spiceFixes.Add([PSCustomObject]@{ Rule = $f.Rule; Count = $f.Count })
        }
    }
    $FileResults.Add([PSCustomObject]@{
        File          = $spicePath
        Changed       = $true
        AppliedFixes  = $spiceFixes
        RemainingHits = @()
        NewContent    = $spiceContent
    })
    if ($spiceFixes.Count -gt 0) {
        $TotalAutoFixes += ($spiceFixes | Measure-Object -Property Count -Sum).Sum
    }
    if ($Apply) {
        Set-Content -LiteralPath $spicePath -Value $spiceContent -NoNewline:$false -Encoding UTF8
        Write-Host "Wrote $spicePath" -ForegroundColor Green
    }
}

# ---------------------------------------------------------------------------
# 5b. Manifest / config JSON load-killer fixes (ManifestFixer)
# ---------------------------------------------------------------------------

if ($ManifestFiles.Count -gt 0) {
    [void](Ensure-ApiMigratorCoreDll)
}

foreach ($file in $ManifestFiles) {
    $original = Get-Content -Raw -LiteralPath $file.FullName -ErrorAction SilentlyContinue
    if ($null -eq $original) { $original = '' }

    $result = Repair-ModManifestContent -Content $original
    $working = $result.Content
    $appliedFixes = New-Object System.Collections.Generic.List[object]
    foreach ($af in $result.Fixes) { $appliedFixes.Add($af) }
    $changed = ($working -ne $original)

    if ($changed) {
        $FileResults.Add([PSCustomObject]@{
            File          = $file.FullName
            Changed       = $changed
            AppliedFixes  = $appliedFixes
            RemainingHits = @()
            NewContent    = $working
        })
        if ($appliedFixes.Count -gt 0) {
            $TotalAutoFixes += ($appliedFixes | Measure-Object -Property Count -Sum).Sum
        }

        if ($Apply) {
            if (-not $NoBackup) {
                $bak = "$($file.FullName).bak"
                if (-not (Test-Path $bak)) {
                    Copy-Item -LiteralPath $file.FullName -Destination $bak -Force -ErrorAction SilentlyContinue
                }
            }
            # UTF-8 no BOM (CoQ / Steam Workshop friendly)
            $utf8 = New-Object System.Text.UTF8Encoding $false
            [System.IO.File]::WriteAllText($file.FullName, $working, $utf8)
        }
    }
}

# ---------------------------------------------------------------------------
# 6. Report
# ---------------------------------------------------------------------------

$reportDir = Split-Path -Parent $Report
if ($reportDir -and -not (Test-Path $reportDir)) {
    New-Item -ItemType Directory -Force -Path $reportDir | Out-Null
}

$mode = if ($Apply) { 'APPLY (files written)' } else { 'DRY-RUN (no files written)' }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# Caves of Qud Obsolete-API Migration Report")
[void]$sb.AppendLine()
[void]$sb.AppendLine("- Mode: **$mode**")
[void]$sb.AppendLine("- Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
[void]$sb.AppendLine("- Dump source: ``$DumpPath`` ($($DumpEntries.Count) entries)")
[void]$sb.AppendLine("- Curated rules source: ``$RulesPath`` ($($CuratedRules.Count) rules)")
[void]$sb.AppendLine("- Scan roots: $($Path -join ', ')")
if ($Mod) { [void]$sb.AppendLine("- Mod filter: ``$Mod``") }
[void]$sb.AppendLine("- Files scanned: $($TargetFiles.Count) .cs/.xml + $($ManifestFiles.Count) manifest/config.json")
[void]$sb.AppendLine("- Files with auto-fixes and/or remaining hits: $($FileResults.Count)")
[void]$sb.AppendLine("- Total auto-fix rewrites: **$TotalAutoFixes**")
[void]$sb.AppendLine("- Total remaining obsolete-pattern hits needing review: **$TotalRemainingHits**")
[void]$sb.AppendLine()
[void]$sb.AppendLine("> Advice never says to add ``[Obsolete]``. PreferXML -> PreferHarmonyPatch -> C# override only when there is no other option. In-place API body fixes are separate.")
[void]$sb.AppendLine()

if ($FileResults.Count -eq 0) {
    [void]$sb.AppendLine("No obsolete-API patterns or auto-fixes found in scope. Clean.")
} else {
    foreach ($fr in $FileResults) {
        [void]$sb.AppendLine("## $($fr.File)")
        [void]$sb.AppendLine()
        if ($fr.AppliedFixes.Count -gt 0) {
            [void]$sb.AppendLine("**Auto-fixes $(if ($Apply) { 'applied' } else { 'that WOULD be applied with -Apply' }):**")
            foreach ($af in $fr.AppliedFixes) {
                [void]$sb.AppendLine("- $($af.Rule) x $($af.Count)")
            }
            [void]$sb.AppendLine()
        }
        if ($fr.RemainingHits.Count -gt 0) {
            [void]$sb.AppendLine("**Remaining hits needing human review:**")
            [void]$sb.AppendLine()
            foreach ($h in $fr.RemainingHits) {
                $codeEsc = ($h.Text -replace '\|', '\|') -replace '`', '\`'
                if ($codeEsc.Length -gt 160) { $codeEsc = $codeEsc.Substring(0, 157) + '...' }
                [void]$sb.AppendLine("- **L$($h.Line)** ``$($h.Member)`` - $($h.Message)")
                [void]$sb.AppendLine("  - Code: ``$codeEsc``")
                $advice = $h.Advice
                if (-not $advice) {
                    $advice = Get-ManualAdvice -Member $h.Member -Message $h.Message -Code $h.Text
                }
                if ($advice) {
                    [void]$sb.AppendLine("  - Advice:")
                    [void]$sb.AppendLine('    ```')
                    foreach ($aline in ($advice -replace "`r`n", "`n") -split "`n") {
                        [void]$sb.AppendLine("    $aline")
                    }
                    [void]$sb.AppendLine('    ```')
                }
            }
            [void]$sb.AppendLine()
        }
    }
}

$sb.ToString() | Set-Content -LiteralPath $Report -Encoding UTF8

Write-Host ""
Write-Host "=== Summary ===" -ForegroundColor Green
Write-Host "Mode:                     $mode"
Write-Host "Files scanned:            $($TargetFiles.Count)"
Write-Host "Files needing attention:  $($FileResults.Count)"
Write-Host "Auto-fix rewrites:        $TotalAutoFixes"
Write-Host "Remaining manual hits:    $TotalRemainingHits"
Write-Host "Report written to:       $Report" -ForegroundColor Yellow

if (-not $Apply -and $TotalAutoFixes -gt 0) {
    Write-Host ""
    Write-Host "This was a dry run. Re-run with -Apply to write the $TotalAutoFixes auto-fix(es) to disk." -ForegroundColor Magenta
}
