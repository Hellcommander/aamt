function Test-InsideLineOrBlockComment {
    param([string]$Content, [int]$Index)
    if ($Index -lt 0 -or $Index -gt $Content.Length) { return $false }
    $i = 0
    $block = 0
    while ($i -lt $Index) {
        $c = $Content[$i]
        if ($c -eq '"' -or $c -eq "'") {
            $i++
            while ($i -lt $Content.Length) {
                if ($Content[$i] -eq '\' ) { $i += 2; continue }
                if ($Content[$i] -eq $c) { $i++; break }
                $i++
            }
            continue
        }
        if ($c -eq '/' -and ($i + 1) -lt $Content.Length) {
            $n = $Content[$i + 1]
            if ($n -eq '/' -and $block -eq 0) {
                $eol = $Content.IndexOf("`n", $i + 2)
                if ($eol -lt 0) { $eol = $Content.Length }
                # Match on this comment line → suppress; otherwise skip past and keep scanning.
                if ($Index -gt $i -and $Index -lt $eol) { return $true }
                $i = $eol
                continue
            }
            if ($n -eq '*') { $block++; $i += 2; continue }
        }
        if ($block -gt 0 -and $c -eq '*' -and ($i + 1) -lt $Content.Length -and $Content[$i + 1] -eq '/') {
            $block--; $i += 2; continue
        }
        $i++
    }
    return ($block -gt 0)
}

function Test-InsideGameTextToken {
    param([string]$Content, [int]$Index)
    if ($Index -le 0 -or $Index -ge $Content.Length) { return $false }
    $lineStart = if ($Index -eq 0) { 0 } else { $Content.LastIndexOf("`n", $Index - 1) + 1 }
    $lineEnd = $Content.IndexOf("`n", $Index)
    if ($lineEnd -lt 0) { $lineEnd = $Content.Length }
    for ($open = $Index - 1; $open -ge $lineStart; $open--) {
        if ($Content[$open] -ne '=') { continue }
        if (($open + 1) -ge $lineEnd) { continue }
        if (-not [char]::IsLetter($Content[$open + 1])) { continue }
        $close = $Content.IndexOf('=', $Index)
        if ($close -lt 0 -or $close -ge $lineEnd) { return $false }
        for ($k = $open + 1; $k -lt $close; $k++) {
            $ch = $Content[$k]
            if ([char]::IsLetterOrDigit($ch)) { continue }
            if ($ch -eq '.' -or $ch -eq '_' -or $ch -eq ':' -or $ch -eq '#' -or $ch -eq "'" -or $ch -eq '-') { continue }
            return $false
        }
        return ($close -gt ($open + 1))
    }
    return $false
}

function Test-InsideStringLiteralSimple {
    param([string]$Content, [int]$Index)
    if ($Index -lt 0 -or $Index -ge $Content.Length) { return $false }
    $i = 0
    while ($i -lt $Index) {
        $c = $Content[$i]
        if ($c -eq '"') {
            $start = $i
            $i++
            while ($i -lt $Content.Length) {
                if ($Content[$i] -eq '\') { $i += 2; continue }
                if ($Content[$i] -eq '"') { $i++; break }
                $i++
            }
            if ($Index -gt $start -and $Index -lt $i) { return $true }
            continue
        }
        if ($c -eq '/' -and ($i + 1) -lt $Content.Length) {
            $n = $Content[$i + 1]
            if ($n -eq '/') {
                $eol = $Content.IndexOf("`n", $i + 2)
                $i = if ($eol -lt 0) { $Content.Length } else { $eol }
                continue
            }
            if ($n -eq '*') {
                $end = $Content.IndexOf('*/', $i + 2)
                $i = if ($end -lt 0) { $Content.Length } else { $end + 2 }
                continue
            }
        }
        $i++
    }
    return $false
}

function Test-ShouldReportHit {
    param($Entry, [string]$Content, $Match)
    $index = $Match.Index
    if (Test-InsideLineOrBlockComment -Content $Content -Index $index) { return $false }
    if (Test-InsideGameTextToken -Content $Content -Index $index) { return $false }
    $isGo = $Entry.type -like '*GameObject'
    if ($isGo -and $ShortGameObjectMembers.Contains([string]$Entry.member)) {
        if (Test-InsideStringLiteralSimple -Content $Content -Index $index) { return $false }
    }
    return $true
}

