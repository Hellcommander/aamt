# Mirror ApiMigrator.Core.RuleEngine — curated keeps 2s; dump scan uses 500ms so a single
# catastrophic pattern cannot pin a file for minutes (626 entries × 2s = 20+ min worst case).
$RegexMatchTimeout = [TimeSpan]::FromSeconds(2)
$DumpRegexMatchTimeout = [TimeSpan]::FromMilliseconds(500)
$RegexNone = [System.Text.RegularExpressions.RegexOptions]::None

function Get-DumpScanNeedle {
    param($Entry)
    # Cheap Ordinal gate before dump regex (mirrors RuleEngine.TryGetDumpScanNeedle).
    $m = [string]$Entry.member
    if ($m.Length -ge 4 -and $m -match '^[A-Za-z_][A-Za-z0-9_]*$') { return $m }
    return $null
}

# Pre-compile a regex per dump entry for the "remaining hits" scan. Matching runs against
# the FULL file content (not line-by-line) so that entries needing surrounding-context
# lookbehind (e.g. ReplaceBuilder.AddObject vs. the unrelated Cell/Inventory.AddObject) work
# correctly across line boundaries; the line number is then derived from the match index.
$DumpRegexes = @(foreach ($e in $DumpEntries) {
    [PSCustomObject]@{
        Entry  = $e
        Needle = Get-DumpScanNeedle -Entry $e
        Regex  = [regex]::new([string]$e.searchPattern, $RegexNone, $DumpRegexMatchTimeout)
    }
})

function Get-LineNumberFromIndex {
    param([string]$Text, [int]$Index)
    # Linear scan — do NOT use [regex]::Matches on a Substring (alloc + ReDoS risk per hit).
    if ($Index -le 0) { return 1 }
    $count = 1
    $lim = [Math]::Min($Index, $Text.Length)
    for ($i = 0; $i -lt $lim; $i++) {
        if ($Text[$i] -eq "`n") { $count++ }
    }
    return $count
}

function Get-LineText {
    param([string]$Text, [int]$Index)
    $start = $Text.LastIndexOf("`n", [Math]::Max($Index - 1, 0))
    if ($start -lt 0) { $start = -1 }
    $end = $Text.IndexOf("`n", $Index)
    if ($end -lt 0) { $end = $Text.Length }
    return $Text.Substring($start + 1, $end - $start - 1).Trim()
}

