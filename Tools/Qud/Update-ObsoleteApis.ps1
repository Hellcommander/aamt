<#
.SYNOPSIS
    Migrates Caves of Qud mod source (.cs / .xml) off obsolete Assembly-CSharp APIs.

.DESCRIPTION
    Loads the persisted obsolete-API dump (data\obsolete_api_dump.json) as the source of
    truth for what is obsolete and what it should become, applies a curated set of
    hand-verified, mechanically-safe rewrites, and reports every remaining obsolete-pattern
    hit that still needs a human (or a follow-up semi-automated pass).

    The dump is NOT regenerated by this script. It was captured once via the scratch\ApiDump
    reflection tool and is checked in at _tools\data\obsolete_api_dump.json. See README.md.

    Dry-run by default. Nothing is written to disk unless -Apply is passed.

.PARAMETER Path
    One or more root folders to scan. Defaults to the Mods folder (parent of _tools).

.PARAMETER IncludeWorkshop
    Also scan the Steam Workshop content folder for CoQ (333640), read-only style (dry-run
    is obviously safe there; -Apply against Workshop content is allowed but not recommended
    since Workshop syncs can clobber local edits).

.PARAMETER Mod
    Convenience filter: only scan subfolder(s) of Path whose folder name matches this
    (wildcards ok), e.g. -Mod "LogSuppressor".

.PARAMETER Apply
    Actually write fixes to disk. Without this switch the tool only reports what it WOULD do.

.PARAMETER NoBackup
    When -Apply is used, a `<file>.bak` copy is written next to any file that gets modified,
    unless this switch is passed.

.PARAMETER Report
    Path to write the Markdown report to. Defaults to
    _tools\reports\ApiMigration_<timestamp>.md

.PARAMETER DumpPath
    Path to the obsolete-API JSON dump. Defaults to _tools\data\obsolete_api_dump.json next
    to this script.

.PARAMETER Exclude
    Additional directory name patterns to exclude, on top of the built-in
    _tools, bin, obj, .git defaults.

.EXAMPLE
    .\Update-ObsoleteApis.ps1 -Mod LogSuppressor
    Dry-run a single mod folder and print/save a report of auto-fixable hits and remaining
    manual-review hits.

.EXAMPLE
    .\Update-ObsoleteApis.ps1 -Mod LogSuppressor -Apply
    Same, but actually rewrites the safe patterns in place (with .bak backups).

.EXAMPLE
    .\Update-ObsoleteApis.ps1 -IncludeWorkshop -Report C:\temp\full_report.md
    Dry-run every local mod plus the Workshop content folder.
#>

