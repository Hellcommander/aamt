# ===== REGISTRY GENERATION =====

function Generate-ItemRegistry {
    Write-Host ""
    Write-Host "Generating Item Registry..." -ForegroundColor Yellow
    
    $registry = @{
        version = "1.0.0"
        generated = Get-Date -Format "yyyy-MM-ddTHH:mm:ssZ"
        itemCategories = @{
            weapons = "$ItemCount generated"
            devices = "$ItemCount generated"
            armor = "$ItemCount generated"
            reactors = "$ItemCount generated"
            ammunition = "3 generated"
        }
        integration = @{
            xmlFiles = @(
                "SpaceWhaleWeapons.xml"
                "SpaceWhaleDevices.xml"
                "SpaceWhaleArmor.xml"
                "SpaceWhaleReactors.xml"
                "SpaceWhaleAmmunition.xml"
            )
            assetSource = $AssetDir
            unidRange = "0xE2000000 - 0xE2000999"
        }
        notes = @(
            "All items use bio-organic space whale technology"
            "Items are compatible with Commonwealth factions"
            "Assets reference Stage4_Final from quality generator"
            "UNIDs are reserved in range 0xE2000000+"
        )
    }
    
    $registryPath = Join-Path $OutputDir "item_registry.json"
    $registry | ConvertTo-Json -Depth 10 | Set-Content $registryPath
    
    Write-Host "  Registry created: $registryPath" -ForegroundColor Green
}

