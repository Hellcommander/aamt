# Space Whale Item Generator
# Creates Transcendence ItemType definitions using generated assets
# Generates: Weapons, Devices, Armor, and Ammunition

param(
    [Parameter(Mandatory=$false)]
    [string]$AssetDir = "Output/SpaceWhaleAssets_HQ/Stage4_Final",
    
    [Parameter(Mandatory=$false)]
    [string]$OutputDir = "Output/Items",
    
    [Parameter(Mandatory=$false)]
    [ValidateSet("All", "Weapons", "Devices", "Armor", "Ammunition", "Reactors")]
    [string]$ItemType = "All",
    
    [Parameter(Mandatory=$false)]
