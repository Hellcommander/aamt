)

$ErrorActionPreference = "Stop"

Write-Host "Space Whale Item Generator" -ForegroundColor Cyan
Write-Host "==========================" -ForegroundColor Cyan
Write-Host ""

# Check if asset directory exists
if (-not (Test-Path $AssetDir)) {
    Write-Host "ERROR: Asset directory not found: $AssetDir" -ForegroundColor Red
    Write-Host "Please run space_whale_quality_asset_generator.py first" -ForegroundColor Yellow
