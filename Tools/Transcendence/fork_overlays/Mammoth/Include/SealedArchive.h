//	SealedArchive.h
//
//	Sealed sound archives (MTSA1, made by the AI asset toolkit's audio_seal.py): one file in an extension's Resources
//	holding its sounds scrambled with a per-entry keystream, so no sound file sits loose in the extension and a .tdb
//	cannot simply be unpacked for them. CResourceDb::LoadSound falls back to the archive when a declared sound file is
//	not in the extension itself. Any extension, library or otherwise, is sealed-ready by shipping Resources\sounds.mtsa
//	next to its XML and declaring its sounds as usual.
//
//	Format, little-endian: "MTSA1\0", 8 bytes key id, u32 count, then per entry u16 nameLen, UTF-8 asset path
//	("/Resources/Audio/x.wav"), u64 offset, u32 size, u64 nonce. Data: entry bytes XOR a splitmix64 keystream seeded
//	with key0 ^ nonce ^ fnv1a64(path as stored), each 64-bit word also ^ key1 (key0, key1 = the key's first two words).
//	The key and its id come from SealedKey.h, generated by audio_seal.py write-cpp-key (never committed).
//	Scrambling against copying and tools, not secrecy: the key is in this build.

#pragma once

#include <cstdint>
#include <cstring>
#include <map>
#include <string>
#include <vector>

#include "SealedKey.h"

namespace SealedArchive
	{
	struct Entry
		{
		std::string sName;			//	path exactly as stored (seeds the keystream)
		uint64_t dwOffset = 0;
		uint32_t dwSize = 0;
		uint64_t dwNonce = 0;
		};

	inline uint64_t ReadU64 (const unsigned char *p)
		{
		uint64_t v = 0;
		for (int i = 7; i >= 0; --i)
			v = (v << 8) | p[i];
		return v;
		}

	inline uint32_t ReadU32 (const unsigned char *p)
		{
		return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
		}

	inline uint64_t Fnv1a64 (const std::string &s)
		{
		uint64_t h = 0xCBF29CE484222325ull;
		for (unsigned char c : s)
			h = (h ^ c) * 0x100000001B3ull;
		return h;
		}

	inline uint64_t SplitMix (uint64_t &state)
		{
		state += 0x9E3779B97F4A7C15ull;
		uint64_t z = state;
		z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
		z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
		return z ^ (z >> 31);
		}

	//	Paths compare case-insensitively with forward slashes and a leading slash: the engine builds
	//	"Resources\Audio\x.wav", the archive stores "/Resources/Audio/x.wav".
	inline std::string NormalizePath (std::string s)
		{
		for (char &c : s)
			{
			if (c == '\\') c = '/';
			else if (c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
			}
		if (s.empty() || s[0] != '/')
			s.insert(s.begin(), '/');
		return s;
		}

	class CArchive
		{
		public:
			//	Parses the index from the whole archive's bytes. False (with a reason) when it is not an archive or was
			//	sealed with another key; then it has no entries.
			//	`modKeyHex`: the extension's own 32-byte key (Resources\sounds.key, as hex), tried when the archive was
			//	not sealed with this build's key, so any extension can ship sealed sounds with a key of its own.
			bool Open (std::vector<unsigned char> bytes, std::string *retsError, const std::string &modKeyHex = std::string())
				{
				m_Bytes = std::move(bytes);
				m_Entries.clear();
				std::memcpy(m_Key, SealedKey::Key, 32);
				if (m_Bytes.size() < 18 || std::memcmp(m_Bytes.data(), "MTSA1\0", 6) != 0)
					return Fail("not a sealed sound archive", retsError);
				if (std::memcmp(m_Bytes.data() + 6, SealedKey::KeyId, 8) != 0)
					{
					unsigned char modKey[32];
					if (!ParseHexKey(modKeyHex, modKey) || !KeyIdMatches(modKey, m_Bytes.data() + 6))
						return Fail("sealed with a different key than this build carries, and no matching sounds.key beside it", retsError);
					std::memcpy(m_Key, modKey, 32);
					}

				const unsigned char *p = m_Bytes.data();
				size_t total = m_Bytes.size();
				size_t pos = 14;
				uint32_t count = ReadU32(p + pos);
				pos += 4;
				for (uint32_t i = 0; i < count; i++)
					{
					if (pos + 2 > total)
						return Fail("truncated archive", retsError);
					uint16_t nameLen = (uint16_t)(p[pos] | (p[pos + 1] << 8));
					pos += 2;
					if (pos + nameLen + 20 > total)
						return Fail("truncated archive", retsError);
					Entry e;
					e.sName.assign((const char *)p + pos, nameLen);
					pos += nameLen;
					e.dwOffset = ReadU64(p + pos);
					e.dwSize = ReadU32(p + pos + 8);
					e.dwNonce = ReadU64(p + pos + 12);
					pos += 20;
					if (e.dwOffset + e.dwSize > total)
						return Fail("entry past the end", retsError);
					m_Entries[NormalizePath(e.sName)] = e;
					}
				return true;
				}

			bool IsOpen (void) const { return !m_Entries.empty(); }
			size_t GetCount (void) const { return m_Entries.size(); }

			//	The unsealed bytes of an entry, or false when the archive has no such path.
			bool Read (const std::string &sPath, std::string *retsData) const
				{
				auto it = m_Entries.find(NormalizePath(sPath));
				if (it == m_Entries.end())
					return false;
				const Entry &e = it->second;
				std::string out((const char *)m_Bytes.data() + e.dwOffset, e.dwSize);
				uint64_t key0 = ReadU64(m_Key);
				uint64_t key1 = ReadU64(m_Key + 8);
				uint64_t state = key0 ^ e.dwNonce ^ Fnv1a64(e.sName);
				size_t n = out.size();
				size_t i = 0;
				for (; i + 8 <= n; i += 8)
					{
					uint64_t ks = SplitMix(state) ^ key1;
					for (int b = 0; b < 8; b++)
						out[i + b] ^= (char)((ks >> (8 * b)) & 0xFF);
					}
				if (i < n)
					{
					uint64_t ks = SplitMix(state) ^ key1;
					for (int b = 0; i + b < n; b++)
						out[i + b] ^= (char)((ks >> (8 * b)) & 0xFF);
					}
				*retsData = std::move(out);
				return true;
				}

		private:
			static bool ParseHexKey (const std::string &hex, unsigned char *out32)
				{
				size_t start = hex.find_first_not_of(" \t\r\n"), end = hex.find_last_not_of(" \t\r\n");
				if (start == std::string::npos || end - start + 1 != 64) return false;
				for (int i = 0; i < 32; i++)
					{
					int v = 0;
					for (int k = 0; k < 2; k++)
						{
						char c = hex[start + 2 * i + k];
						int d = (c >= '0' && c <= '9') ? c - '0' : (c >= 'a' && c <= 'f') ? c - 'a' + 10 : (c >= 'A' && c <= 'F') ? c - 'A' + 10 : -1;
						if (d < 0) return false;
						v = v * 16 + d;
						}
					out32[i] = (unsigned char)v;
					}
				return true;
				}

			//	Key id = first 8 bytes of SHA-256(key). A small SHA-256, so the header needs no engine dependency.
			static bool KeyIdMatches (const unsigned char *key32, const unsigned char *id8)
				{
				static const uint32_t K[64] = {
					0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,
					0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,
					0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,
					0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2 };
				uint32_t h[8] = { 0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19 };
				unsigned char block[64] = { 0 };
				std::memcpy(block, key32, 32);
				block[32] = 0x80;
				block[63] = 0x00; block[62] = 0x01;	//	bit length 256 = 0x0100
				uint32_t w[64];
				for (int i = 0; i < 16; i++) w[i] = ((uint32_t)block[4*i] << 24) | ((uint32_t)block[4*i+1] << 16) | ((uint32_t)block[4*i+2] << 8) | block[4*i+3];
				auto rotr = [](uint32_t x, int n) { return (x >> n) | (x << (32 - n)); };
				for (int i = 16; i < 64; i++)
					{
					uint32_t s0 = rotr(w[i-15], 7) ^ rotr(w[i-15], 18) ^ (w[i-15] >> 3);
					uint32_t s1 = rotr(w[i-2], 17) ^ rotr(w[i-2], 19) ^ (w[i-2] >> 10);
					w[i] = w[i-16] + s0 + w[i-7] + s1;
					}
				uint32_t a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
				for (int i = 0; i < 64; i++)
					{
					uint32_t S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
					uint32_t ch = (e & f) ^ (~e & g);
					uint32_t t1 = hh + S1 + ch + K[i] + w[i];
					uint32_t S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
					uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
					uint32_t t2 = S0 + maj;
					hh = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
					}
				h[0] += a; h[1] += b;
				unsigned char id[8] = { (unsigned char)(h[0] >> 24), (unsigned char)(h[0] >> 16), (unsigned char)(h[0] >> 8), (unsigned char)h[0],
										(unsigned char)(h[1] >> 24), (unsigned char)(h[1] >> 16), (unsigned char)(h[1] >> 8), (unsigned char)h[1] };
				return std::memcmp(id, id8, 8) == 0;
				}

			unsigned char m_Key[32];

			bool Fail (const char *pszReason, std::string *retsError)
				{
				if (retsError) *retsError = pszReason;
				m_Entries.clear();
				return false;
				}

			std::vector<unsigned char> m_Bytes;
			std::map<std::string, Entry> m_Entries;
		};
	}
