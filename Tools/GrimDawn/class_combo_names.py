#!/usr/bin/env python3
"""Generate tagSkillClassName combo names for all mastery pairs (gaps only).

Mastery names come from the game/mod text (class tree -> mastery skill ->
skillDisplayName tag), so mod classes get real names instead of path guesses.
Missing pairs get a placeholder, then optionally a name from a local Ollama
model. Ollama names are cached in work/combo_name_cache.json so rebuilds after
a patch keep the same names without re-querying.
"""

from __future__ import annotations

