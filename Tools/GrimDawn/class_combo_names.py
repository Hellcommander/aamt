import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

try:
    import requests
except ImportError:
    requests = None  # type: ignore

COMMON_DIR = Path(__file__).resolve().parent.parent / "Common"
if COMMON_DIR.is_dir() and str(COMMON_DIR) not in sys.path:
    sys.path.insert(0, str(COMMON_DIR))

TOOLS_DIR = Path(__file__).resolve().parent
NAME_CACHE = TOOLS_DIR / "work" / "combo_name_cache.json"
DEFAULT_OLLAMA_HOST = "http://127.0.0.1:11434"

TAG_RE = re.compile(r"^(tagSkillClassName\w+)\s+(.+)$", re.IGNORECASE)
TAG_EQ_RE = re.compile(r"^(tagSkillClassName\w+)\s*=\s*(.+)$", re.IGNORECASE)
ANY_TAG_RE = re.compile(r"^(tag\w+)\s*=\s*(.*)$", re.IGNORECASE)
COMBO_TAG_RE = re.compile(r"^tagSkillClassName(\d{2,3})(\d{2,3})$", re.IGNORECASE)

# Files this toolkit writes; never harvested as "existing" so bad output can be regenerated
GENERATED_MARKER = "// generated by class_combo_names.py"
GENERATED_FILES = {"tags_kitchen_sink_combos.txt", "tags_survival_foa.txt", "tags_mod_combos.txt"}

DEFAULT_MASTERIES = {
    "01": "Soldier",
    "02": "Demolitionist",
    "03": "Occultist",
    "04": "Nightblade",
    "05": "Arcanist",
    "06": "Shaman",
    "07": "Inquisitor",
    "08": "Necromancer",
    "09": "Oathkeeper",
    "10": "Berserker",
}

OLLAMA_BATCH = 20
PREFERRED_MODEL_HINTS = ("llama3", "qwen", "mistral", "gemma", "phi", "llama")
CODE_MODEL_HINTS = ("code", "coder", "starcoder", "deepseek-coder")


# ---------------------------------------------------------------- tag files

def _is_generated(path: Path) -> bool:
    if path.name.lower() in GENERATED_FILES:
        return True
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            return fh.readline().strip().startswith(GENERATED_MARKER)
    except OSError:
        return False


def parse_tag_file(path: Path) -> Dict[str, str]:
    out: Dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if not s or s.startswith("//") or s.startswith("#"):
            continue
        m = TAG_EQ_RE.match(s) or TAG_RE.match(s)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def _iter_tag_files(roots: Iterable[Path], *, include_generated: bool) -> Iterable[Path]:
    for root in roots:
        if not root or not Path(root).exists():
            continue
        root = Path(root)
        files = [root] if root.is_file() else root.rglob("*.txt")
        for path in files:
            if include_generated or not _is_generated(path):
                yield path


def collect_tags(roots: List[Path], *, include_generated: bool = False) -> Dict[str, str]:
    """Combo/class-name tags (tagSkillClassName*) from text roots."""
    tags: Dict[str, str] = {}
    for path in _iter_tag_files(roots, include_generated=include_generated):
        tags.update(parse_tag_file(path))
    return tags


def collect_all_text_tags(roots: Iterable[Path]) -> Dict[str, str]:
    """Every tag=value pair (lower-cased keys) for resolving display names."""
    tags: Dict[str, str] = {}
    for path in _iter_tag_files(roots, include_generated=False):
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = ANY_TAG_RE.match(line.strip())
            if m:
                tags[m.group(1).lower()] = m.group(2).strip()
    return tags


def extract_text_roots(
    game_dir: Path, mod_roots: Sequence[Path], work: Path, *, include_game: bool = True
) -> List[Path]:
    """Unpack Text_EN.arc of the game, every DLC and the given mods (cached by file stamp)."""
    from gd_paths import GamePaths, iter_arc_in_mod

    game = GamePaths(Path(game_dir))
    arcs: List[Tuple[str, Path]] = []
    if include_game:
        arcs = [(f"game_{i}_{a.parent.parent.name}", a) for i, a in enumerate(game.text_arcs("EN"))]
    for mod in mod_roots:
        for arc in iter_arc_in_mod(Path(mod)):
            if arc.name.lower() == "text_en.arc":
                arcs.append((f"mod_{Path(mod).name}", arc))
    return _extract_arcs(game.game_dir, arcs, work)


def mod_text_roots(game_dir: Optional[Path], mod_root: Path, work: Path) -> List[Path]:
    """Loose text folders of a mod plus its unpacked Text_EN.arc."""
    roots = [
        p
        for p in (
            mod_root / "localization",
            mod_root / "resources" / "text_en",
            mod_root / "resources" / "Text_EN",
            mod_root / "source" / "text_en",
        )
        if p.is_dir()
    ]
    if game_dir:
        roots.extend(extract_text_roots(game_dir, [mod_root], work, include_game=False))
    return roots


def _extract_arcs(game_dir: Path, arcs: Sequence[Tuple[str, Path]], work: Path) -> List[Path]:
    from archive_tool import ArchiveTool, kill_orphan_archivetool
    from gd_paths import file_stamp

    roots: List[Path] = []
    tool = None
    for label, arc in arcs:
        dest = work / "_text_cache" / re.sub(r"[^\w.-]+", "_", label)
        marker = dest / ".stamp"
        stamp = file_stamp([arc])
        if not (marker.is_file() and marker.read_text(encoding="utf-8") == stamp):
            tool = tool or ArchiveTool(Path(game_dir))
            if dest.exists():
                shutil.rmtree(dest)
            dest.mkdir(parents=True)
            try:
                tool.extract_arc(arc, dest)
                marker.write_text(stamp, encoding="utf-8")
            except Exception as exc:
                print(f"WARN: could not unpack {arc}: {exc}", file=sys.stderr)
                continue
        roots.append(dest)
    if tool:
        kill_orphan_archivetool()
    return roots


# ---------------------------------------------------------------- masteries

def _clean_display_name(raw: str) -> str:
    s = re.sub(r"\{[^}]*\}|\^[a-zA-Z]", "", raw or "").strip()
    s = re.sub(r"\s+mastery$", "", s, flags=re.I).strip()
    return s


def _pretty_from_path(tree_rel: str) -> str:
    t = tree_rel.replace("\\", "/").lower()
    m = re.search(r"playerclass(\d{2})/", t)
    if m and m.group(1) in DEFAULT_MASTERIES:
        return DEFAULT_MASTERIES[m.group(1)]
    # Use the folder holding the tree (records/<pack>/skills/<class>/_classtree_x.dbr)
    parts = [p for p in t.split("/") if p]
    folder = parts[-2] if len(parts) >= 2 else Path(t).stem
    stem = re.sub(r"^_?classtree_?", "", Path(t).stem)
    name = folder
    for prefix in ("playerclass", "zenithclass", "ddclass", "class"):
        if name.startswith(prefix) and len(name) > len(prefix):
            name = name[len(prefix):]
            break
    name = re.sub(r"class$", "", name) or name
    if name.isdigit() or not name:
        name = re.sub(r"^class", "", stem) or stem
    return name.replace("_", " ").title().replace(" ", "") or "Unknown"


def mastery_display_name(mod_db: Path, tree_rel: str, text_tags: Dict[str, str]) -> Optional[str]:
    """class tree -> skillName1 (mastery skill) -> skillDisplayName tag -> text."""
    from dbr_io import read_dbr

    tree = mod_db / tree_rel.replace("\\", "/")
    if not tree.is_file() or not text_tags:
        return None
    try:
        mastery_rel = read_dbr(tree).get("skillName1", "").strip()
        if not mastery_rel:
            return None
        mastery = mod_db / mastery_rel.replace("\\", "/")
        if not mastery.is_file():
            return None
        tag = read_dbr(mastery).get("skillDisplayName", "").strip().lower()
    except Exception:
        return None
    name = _clean_display_name(text_tags.get(tag, "")) if tag else ""
    return name or None


def discover_mastery_ids(
    mod_db: Path,
    text_tags: Optional[Dict[str, str]] = None,
    roster: Optional[Sequence[str]] = None,
) -> Dict[str, str]:
    """PC skillTree order (or an explicit roster) as 01..N (matches class UI slots) -> name."""
    from dbr_io import get_list_field, read_dbr

    found = dict(DEFAULT_MASTERIES)
    pc = mod_db / "records/creatures/pc/malepc01.dbr"
    if roster is not None or pc.is_file():
        trees = list(roster) if roster is not None else get_list_field(read_dbr(pc), "skillTree")
        if trees:
            found = {}
        for i, tree in enumerate(trees):
            mid = f"{i + 1:02d}"
            name = mastery_display_name(mod_db, tree, text_tags or {})
            if not name:
                tl = tree.replace("\\", "/").lower()
                name = (
                    DEFAULT_MASTERIES[mid]
                    if mid in DEFAULT_MASTERIES and f"playerclass{mid}/" in tl
                    else _pretty_from_path(tree)
                )
            found[mid] = name
        return found

    for p in mod_db.rglob("*"):
        m = re.search(r"playerclass(\d{2})|class(\d{2})", p.name.lower())
        if m:
            mid = m.group(1) or m.group(2)
            found.setdefault(mid, f"Class{mid}")
    return found


def _tag_for_pair(a: str, b: str) -> Tuple[str, str]:
    x, y = sorted([a, b], key=lambda s: (len(s), s))
    return f"tagSkillClassName{x}{y}", f"tagSkillClassName{y}{x}"


def missing_berserker_combos(
    tags: Dict[str, str], masteries: Dict[str, str], berserker_id: str = "10"
) -> List[Tuple[str, str, str]]:
    return missing_combos_for_ids(tags, masteries, anchor_id=berserker_id)


def missing_all_combos(
    tags: Dict[str, str], masteries: Dict[str, str]
) -> List[Tuple[str, str, str]]:
    return missing_combos_for_ids(tags, masteries, anchor_id=None)


def missing_combos_for_ids(
    tags: Dict[str, str],
    masteries: Dict[str, str],
    *,
    anchor_id: Optional[str] = None,
) -> List[Tuple[str, str, str]]:
    missing: List[Tuple[str, str, str]] = []
    existing = {k.lower() for k in tags}
    ids = sorted(masteries.keys(), key=lambda s: (len(s), s))
    if anchor_id:
        if anchor_id not in masteries:
            return []
        pairs = [(anchor_id, p) for p in ids if p != anchor_id]
    else:
        pairs = [(ids[i], ids[j]) for i in range(len(ids)) for j in range(i + 1, len(ids))]

    for a, b in pairs:
        tag, alt = _tag_for_pair(a, b)
        if tag.lower() not in existing and alt.lower() not in existing:
            missing.append((tag, masteries.get(a, a), masteries.get(b, b)))
    return missing


def pair_names(combo_tags: Dict[str, str], names_by_id: Dict[str, str]) -> Dict[str, str]:
    """Index-based combo tags -> {'a|b' mastery-name pair: combo name} for one roster."""
    out: Dict[str, str] = {}
    for tag, name in combo_tags.items():
        m = COMBO_TAG_RE.match(tag)
        if not m or not name.strip():
            continue
        a, b = names_by_id.get(m.group(1)), names_by_id.get(m.group(2))
        if a and b and a.lower() != b.lower() and not is_placeholder_name(name, a, b):
            out[_pair_key(a, b)] = name.strip()
    return out


def is_placeholder_name(name: str, a: str, b: str) -> bool:
    """Mod-author stand-ins like 'Soldier sparker' or '?'; official names never contain a class name."""
    n = name.strip().lower()
    if not n or n in ("?", "-", "tbd", "placeholder") or n.replace(" ", "") == (a + b).lower().replace(" ", ""):
        return True
    words = set(re.findall(r"[a-z']+", n))
    return any(w in words for cls in (a, b) for w in re.findall(r"[a-z']+", cls.lower()) if len(w) > 3)


class ComboSource:
    """A mod whose own combo tags should keep their names after classes are renumbered."""

    def __init__(self, label: str, db: Path, text_roots: Sequence[Path], roster: Optional[List[str]] = None):
        self.label = label
        self.db = Path(db)
        self.text_roots = [Path(p) for p in text_roots]
        self.roster = roster


def official_examples(
    tags: Dict[str, str], masteries: Dict[str, str], limit: int = 12
) -> List[str]:
    """'Soldier + Berserker = Thane' lines from real combo tags, for prompt style."""
    out: List[str] = []
    for tag, name in tags.items():
        m = COMBO_TAG_RE.match(tag)
        if not m:
            continue
        a, b = masteries.get(m.group(1)), masteries.get(m.group(2))
        if a and b and name:
            out.append(f"{a} + {b} = {name}")
        if len(out) >= limit:
            break
    return out


# ---------------------------------------------------------------- ollama

def _ollama_exe() -> Optional[str]:
    exe = shutil.which("ollama")
    if exe:
        return exe
    cand = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Ollama" / "ollama.exe"
    return str(cand) if cand.is_file() else None


def ensure_ollama(host: str = DEFAULT_OLLAMA_HOST, *, autostart: bool = True) -> List[str]:
    """Return installed model names; start `ollama serve` if it isn't running."""
    if requests is None:
        raise RuntimeError("requests package required for Ollama calls (pip install requests)")

    def tags() -> Optional[List[str]]:
        try:
            r = requests.get(f"{host.rstrip('/')}/api/tags", timeout=5)
            r.raise_for_status()
            return [m.get("name", "") for m in r.json().get("models", [])]
        except Exception:
            return None

    models = tags()
    if models is not None:
        return models
    exe = _ollama_exe() if autostart else None
    if not exe:
        raise RuntimeError(f"Ollama not reachable at {host} (and not found to auto-start)")
    print("Ollama not running; starting `ollama serve` ...", flush=True)
    flags = getattr(subprocess, "CREATE_NO_WINDOW", 0) | getattr(subprocess, "DETACHED_PROCESS", 0)
    subprocess.Popen(
        [exe, "serve"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        creationflags=flags,
    )
    for _ in range(30):
        time.sleep(1)
        models = tags()
        if models is not None:
            return models
    raise RuntimeError(f"Started Ollama but {host} did not answer within 30s")


def resolve_ollama_model(explicit: Optional[str], installed: Optional[List[str]] = None) -> str:
    if explicit:
        return explicit
    routed = None
    try:
        from ollama_model_router import get_router

        routed = get_router().get_model_for_task("visual")
    except Exception:
        pass
    if routed and (installed is None or routed in installed):
        return routed
    if installed:
        general = [m for m in installed if not any(h in m.lower() for h in CODE_MODEL_HINTS)]
        for hint in PREFERRED_MODEL_HINTS:
            for m in general:
                if hint in m.lower():
                    return m
        return (general or installed)[0]
    return "llama3.1:8b"


def ollama_options(model: str) -> Dict:
    try:
        from ollama_model_router import get_router

        return get_router().get_ollama_api_options(
            model_name=model,
            temperature=0.85,
            top_p=0.9,
            num_predict=1024,
        )
    except Exception:
        return {"temperature": 0.85, "top_p": 0.9}


NAME_OK_RE = re.compile(r"^[A-Za-z][A-Za-z' -]{1,22}[A-Za-z]$")


def _sanitize_name(raw: object, a: str, b: str) -> Optional[str]:
    if not isinstance(raw, str):
        return None
    s = raw.strip().strip("\"'.").strip()
    s = re.sub(r"\s+", " ", s)
    if not NAME_OK_RE.match(s) or len(s.split()) > 3:
        return None
    if s.lower() in (a.lower(), b.lower(), f"{a}{b}".lower()):
        return None
    # no mash-ups of the class names ("Berspark", "Arcanistrike"): official names never do that
    low = s.lower().replace(" ", "")
    stems = [w[:5] for cls in (a, b) for w in re.findall(r"[a-z]+", cls.lower()) if len(w) >= 5]
    if any(st in low for st in stems):
        return None
    return s


def ollama_generate(
    model: str,
    pairs: List[Tuple[str, str, str]],
    host: str = DEFAULT_OLLAMA_HOST,
    examples: Optional[List[str]] = None,
    taken: Optional[Iterable[str]] = None,
    on_batch=None,
) -> Dict[str, str]:
    """Ask Ollama for names; only keys we asked for and names that pass validation are kept."""
    if requests is None:
        raise RuntimeError("requests package required for Ollama calls")
    out: Dict[str, str] = {}
    used = {t.lower() for t in (taken or [])}
    rejected = 0
    style = "\n".join(f"- {e}" for e in (examples or [])) or (
        "- Soldier + Berserker = Thane\n- Occultist + Berserker = Mystic\n- Nightblade + Berserker = Reaver"
    )
    for i in range(0, len(pairs), OLLAMA_BATCH):
        batch = pairs[i : i + OLLAMA_BATCH]
        wanted = {tag.lower(): (tag, a, b) for tag, a, b in batch}
        prompt = (
            "You name Grim Dawn dual-mastery class combinations.\n"
            "Each name is ONE evocative fantasy title (one word, at most two), "
            "never just the two mastery names glued together, and every name is unique.\n"
            f"Official examples:\n{style}\n\n"
            "Return ONLY a JSON object mapping each tag to its name.\n"
            "Pairs:\n" + "\n".join(f"- {tag}: {a} + {b}" for tag, a, b in batch)
        )
        payload = {
            "model": model,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            "options": ollama_options(model),
        }
        r = requests.post(f"{host.rstrip('/')}/api/generate", json=payload, timeout=300)
        r.raise_for_status()
        raw = r.json().get("response", "{}")
        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            m = re.search(r"\{.*\}", raw, re.S)
            data = json.loads(m.group(0)) if m else {}
        if not isinstance(data, dict):
            data = {}
        for key, value in data.items():
            hit = wanted.get(str(key).strip().lower())
            if not hit:
                rejected += 1
                continue
            tag, a, b = hit
            name = _sanitize_name(value, a, b)
            if not name or name.lower() in used:
                rejected += 1
                continue
            used.add(name.lower())
            out[tag] = name
        print(f"  Ollama batch {i // OLLAMA_BATCH + 1}: {len(out)} accepted so far", flush=True)
        if on_batch:
            on_batch(out)
    if rejected:
        print(f"  Ollama: rejected {rejected} invalid/duplicate names (placeholders kept)", flush=True)
    return out


# ---------------------------------------------------------------- cache + output

def _pair_key(a: str, b: str) -> str:
    return "|".join(sorted([a.lower(), b.lower()]))


def load_name_cache(path: Path = NAME_CACHE) -> Dict[str, str]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def save_name_cache(cache: Dict[str, str], path: Path = NAME_CACHE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(cache, indent=1, sort_keys=True), encoding="utf-8")


def placeholder_names(pairs: List[Tuple[str, str, str]]) -> Dict[str, str]:
    return {tag: f"{a}{b}" for tag, a, b in pairs}


def write_tags(path: Path, new_tags: Dict[str, str], existing: Optional[Dict[str, str]] = None) -> None:
    """Write a generated tag file in the game's `tag=value` format (replaces old output)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    skip = {k.lower() for k in (existing or {})}
    lines = [GENERATED_MARKER + " -- regenerate instead of editing"]
    for tag, name in sorted(new_tags.items()):
        if tag.lower() in skip:
            continue
        lines.append(f"{tag}={name}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def harvest_tag_roots(
    mod_db: Path,
    out_mod: Path,
    game_mods: Optional[Path] = None,
) -> List[Path]:
    roots: List[Path] = [
        mod_db,
        out_mod / "localization",
        out_mod / "resources",
        out_mod / "source",
    ]
    if game_mods and game_mods.is_dir():
        for name in ("grimarillion", "dom", "Rebirth", "Nydiamar", "ReignOfTerror"):
            base = game_mods / name
            for sub in (
                base / "resources" / "text_en",
                base / "resources" / "Text_EN",
                base / "localization",
                base / "source" / "text_en",
            ):
                if sub.is_dir():
                    roots.append(sub)
    return roots


def generate_combo_tags(
    mod_db: Path,
    out_tags: Path,
    *,
    game_dir: Optional[Path] = None,
    text_mods: Sequence[Path] = (),
    sources: Sequence[ComboSource] = (),
    extra_roots: Sequence[Path] = (),
    use_ollama: bool = False,
    model: Optional[str] = None,
    host: str = DEFAULT_OLLAMA_HOST,
    limit: int = -1,
    berserker_only: bool = False,
    work: Optional[Path] = None,
) -> Tuple[int, Dict[str, str]]:
    """
    Write a tag for EVERY mastery pair of the final roster into `out_tags`.

    Combo tags are index-based (tagSkillClassName0110 = class 01 + class 10), and every
    mod numbers its classes differently, so names are matched by mastery-name pair:
    official game names, then each source mod read against its *own* roster (later
    sources win), then the Ollama cache, then Ollama, then a placeholder.
    Returns (written, masteries).
    """
    work = work or (TOOLS_DIR / "work")
    out_mod = out_tags.parent.parent if out_tags.parent.name == "localization" else out_tags.parent
    game_roots = extract_text_roots(Path(game_dir), [], work) if game_dir else []
    game_tags = collect_all_text_tags(game_roots)

    target_roots = [*harvest_tag_roots(mod_db, out_mod), *map(Path, extra_roots)]
    if game_dir:
        target_roots.extend(mod_text_roots(Path(game_dir), out_mod, work))
    for mod in text_mods:
        target_roots.extend(mod_text_roots(Path(game_dir) if game_dir else None, Path(mod), work))
    text_tags = {**game_tags, **collect_all_text_tags(target_roots)}
    masteries = discover_mastery_ids(mod_db, text_tags)

    # name-pair dictionary: official first, then sources (low -> high priority)
    known: Dict[str, str] = {}
    official = collect_tags(game_roots)
    known.update(pair_names(official, DEFAULT_MASTERIES))
    for src in sources:
        src_tags = {**game_tags, **collect_all_text_tags(src.text_roots)}
        src_ids = discover_mastery_ids(src.db, src_tags, src.roster)
        known.update(pair_names(collect_tags(src.text_roots), src_ids))
    if not sources:
        # Single mod: its own text matches its own numbering for the lines it kept
        known.update(pair_names(collect_tags(target_roots), masteries))

    ids = sorted(masteries, key=lambda s: (len(s), s))
    anchor = "10" if berserker_only else None
    pairs = [
        (ids[i], ids[j])
        for i in range(len(ids))
        for j in range(i + 1, len(ids))
        if anchor is None or anchor in (ids[i], ids[j])
    ]
    cache = load_name_cache()
    generated: Dict[str, str] = {}
    missing: List[Tuple[str, str, str]] = []
    from_known = from_cache = 0
    for x, y in pairs:
        a, b = masteries[x], masteries[y]
        tag = _tag_for_pair(x, y)[0]
        key = _pair_key(a, b)
        if key in known:
            generated[tag] = known[key]
            from_known += 1
        elif key in cache:
            generated[tag] = cache[key]
            from_cache += 1
        else:
            generated[tag] = f"{a}{b}"
            missing.append((tag, a, b))
    print(
        f"Masteries: {len(masteries)}  pairs: {len(pairs)}  named by game/mods: {from_known}  "
        f"cached: {from_cache}  unnamed: {len(missing)}",
        flush=True,
    )

    if use_ollama and limit != 0 and missing:
        todo = missing if limit < 0 else missing[:limit]
        try:
            installed = ensure_ollama(host)
            m = resolve_ollama_model(model, installed)
            print(f"Ollama model: {m} (naming {len(todo)} / {len(missing)} pairs)", flush=True)
            by_tag = {t: (a, b) for t, a, b in todo}

            def remember(named: Dict[str, str]) -> None:
                for tag, name in named.items():
                    generated[tag] = name
                    cache[_pair_key(*by_tag[tag])] = name
                save_name_cache(cache)  # resumable if a long run is stopped

            taken = list(generated.values()) + list(masteries.values())
            examples = official_examples(official, DEFAULT_MASTERIES)
            named = ollama_generate(m, todo, host, examples, taken, on_batch=remember)
            remember(named)
            for attempt in range(3):  # re-ask for rejected/missing names
                retry = [p for p in todo if p[0] not in named]
                if not retry:
                    break
                print(f"  retry {attempt + 1}: {len(retry)} rejected pairs", flush=True)
                again = ollama_generate(m, retry, host, examples, taken + list(named.values()), on_batch=remember)
                remember(again)
                named.update(again)
        except Exception as exc:
            print(f"Ollama failed ({exc}); keeping placeholders", file=sys.stderr)

    write_tags(out_tags, generated)
    print(f"Wrote {len(generated)} tags -> {out_tags}", flush=True)
    return len(generated), masteries


def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(description="Generate dual-class combo name tags")
    p.add_argument("--mod-db", required=True)
    p.add_argument("--tag-roots", nargs="*", default=[])
    p.add_argument("--out-tags", required=True)
    p.add_argument("--game", default=None, help="Game dir; also reads official Text_EN.arc names")
    p.add_argument("--game-mods", default=None, help=argparse.SUPPRESS)
    p.add_argument("--berserker-only", action="store_true")
    p.add_argument("--ollama-model", default=None)
    p.add_argument("--ollama-host", default=DEFAULT_OLLAMA_HOST)
    p.add_argument("--dry-run-names", action="store_true", help="Placeholders/cache only")
    p.add_argument(
        "--ollama-limit",
        type=int,
        default=-1,
        help="Ollama-name at most N uncached pairs (0=none, -1=all)",
    )
    args = p.parse_args(argv)

    game = args.game or (str(Path(args.game_mods).parent) if args.game_mods else None)
    generate_combo_tags(
        Path(args.mod_db),
        Path(args.out_tags),
        game_dir=Path(game) if game else None,
        extra_roots=args.tag_roots,
        use_ollama=not args.dry_run_names,
        model=args.ollama_model,
        host=args.ollama_host,
        limit=args.ollama_limit,
        berserker_only=args.berserker_only,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
