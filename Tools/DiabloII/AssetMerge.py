"""Fragment rows for the AssetMerge D2RLoader plugin (`<game>\\mods\\AssetMerge`).

Two game files are binary wholes that D2RMM cannot merge: `hd/model_lod_desc.bin` (the HD model
index) and `global/animdata.d2` (legacy animation timing). With the AssetMerge plugin a mod no
longer ships either file. It appends rows to text fragments that D2RMM merges like any text file:

    global/excel/d2rloader/assetmerge/models.txt     model donor lod mesh minx miny minz maxx maxy maxz
    global/excel/d2rloader/assetmerge/animdata.txt   name source frames speed events

and the plugin builds the merged index and table when the game loads them.

A mod.js cannot compute bounding boxes (they come from the mod's model files), so this tool writes
the rows into the mod's mod.js as a generated block:

    // <assetmerge:models> ... function assetMergeModels() { return {...}; } ... // </assetmerge:models>
    // <assetmerge:lib>    ... function assetMergeWrite(fragment) { readTxt, append, writeTxt } ...

and the mod calls `assetMergeWrite(assetMergeModels())` where it installs its models (function
declarations, so the blocks can sit anywhere in mod.js).

Rows:
  models.txt   one row per mesh: the model path (data/hd/.../name.model, no _lodN), its donor
               (a model already in the index: the new entry copies its record, LOD and mesh rows),
               lod and mesh number and the mesh's bounding box. A row with lod and mesh empty only
               names the donor (its boxes are kept). The model's box is the union of its meshes.
  animdata.txt name = COF name (token + mode + weapon class, e.g. SIS1HTH, AIS41HT); source = an
               entry to copy (optional); frames, speed (256 = one frame per tick) override it;
               events = "-" (none) or frame:code pairs ("6:1"; 1 attack, 2 missile, 3 sound, 4 skill).
  A later row for the same model/mesh or name replaces an earlier one; entries already in the
  game's file are replaced.

Command line:
  python AssetMerge.py models --mod <mod folder> [--game <game>] [--print]
      rows for the models in the mod's model_index.json (entries without "source"); checks them
      against the game's index (donor exists, LOD and mesh counts match) and writes the block into
      <mod>/mod.js (--print: only print the fragment text).
  python AssetMerge.py animdata --mod <mod folder> --rows <json file> [--print]
      rows given as [{"name":..., "source":..., "frames":..., "speed":..., "events":...}].
  python AssetMerge.py merge --models <index.bin> <models.txt> --out <file>   (offline preview,
      the same merge the plugin does, using ModelLodDesc.clone)
"""
import argparse
import json
import os
import re
import sys

MODELS_HEADER = ['model', 'donor', 'lod', 'mesh', 'minx', 'miny', 'minz', 'maxx', 'maxy', 'maxz']
ANIMDATA_HEADER = ['name', 'source', 'frames', 'speed', 'events']

KINDS = {
    'models': ('models.txt', MODELS_HEADER, 'assetMergeModels'),
    'animdata': ('animdata.txt', ANIMDATA_HEADER, 'assetMergeAnimData'),
}

LIB = """// <assetmerge:lib> generated by the toolkit's AssetMerge.py; rerun it instead of editing.
// Appends a fragment's rows to the AssetMerge plugin's merged text file (other mods' rows kept).
function assetMergeWrite(fragment) {
  const path = `global\\\\excel\\\\d2rloader\\\\assetmerge\\\\${fragment.file}`;
  let lines = [];
  try {
    lines = D2RMM.readTxt(path).replace(/\\r/g, '').split('\\n').filter((l) => l.trim().length);
  } catch (e) {
    lines = [];
  }
  if (!lines.length) lines.push(fragment.header);
  else if (lines[0] !== fragment.header) throw new Error(`AssetMerge: ${path} has the header "${lines[0]}", expected "${fragment.header}"`);
  fragment.rows.forEach((row) => lines.push(row));
  D2RMM.writeTxt(path, `${lines.join('\\n')}\\n`);
}
// </assetmerge:lib>
"""


def fmt(v):
    """A float32 value written so that strtod gives the same float back."""
    import numpy as np
    return np.format_float_positional(np.float32(v), unique=True, trim='-') if isinstance(v, float) else str(v)


def model_rows(mod_dir, models):
    import ModelLodDesc
    rows = []
    for item in models:
        if item.get('source'):
            continue  # another mod's model: that mod writes its own rows
        boxes = ModelLodDesc.model_boxes(mod_dir, item['model'])
        for lod, meshes in enumerate(boxes):
            for mesh, (low, high) in enumerate(meshes):
                rows.append([item['model'], item['donor'], lod, mesh] + [fmt(float(v)) for v in list(low) + list(high)])
    return rows


def check_models(archive, rows):
    """Runs the plugin's merge on the game's own index; raises on a row the plugin would reject."""
    import ModelLodDesc
    desc = ModelLodDesc.ModelLodDesc(archive.read(ModelLodDesc.INDEX))
    return apply_models(desc, rows)


def apply_models(desc, rows):
    """The plugin's merge in Python: rows grouped by model in first-appearance order."""
    order, donors, boxes = [], {}, {}
    for row in rows:
        model = row[0].replace('\\', '/').lower()
        if model not in donors:
            order.append(model)
            donors[model], boxes[model] = None, {}
        if row[1]:
            donors[model] = row[1].replace('\\', '/').lower()
        if str(row[2]) != '' and str(row[3]) != '':
            boxes[model][(int(row[2]), int(row[3]))] = ([float(v) for v in row[4:7]], [float(v) for v in row[7:10]])
    for model in order:
        d = desc.find(donors[model])
        if d is None:
            raise KeyError(f'{model}: donor {donors[model]} is not in the game\'s model index')
        lods = [list(desc._mesh_rows(lod)) for lod in desc._lod_rows(d)]
        full = [[boxes[model].get((k, m)) for m in range(len(meshes))] for k, meshes in enumerate(lods)]
        for (k, m) in boxes[model]:
            if k >= len(lods) or m >= len(lods[k]):
                raise ValueError(f'{model}: box for LOD {k} mesh {m}, but donor {donors[model]} has {[len(x) for x in lods]} meshes per LOD')
        if not boxes[model]:
            desc.clone(donors[model], model)
            continue
        donor_info = desc.describe(donors[model])
        filled = [[full[k][m] or (donor_info['lods'][k][m]['box'][:3], donor_info['lods'][k][m]['box'][3:]) for m in range(len(full[k]))] for k in range(len(full))]
        desc.clone(donors[model], model, filled)
    return desc


def fragment_text(kind, rows):
    header = KINDS[kind][1]
    return '\n'.join(['\t'.join(header)] + ['\t'.join(str(c) for c in r) for r in rows]) + '\n'


def js_block(kind, rows, note=''):
    file, header, func = KINDS[kind]
    body = ',\n'.join('      ' + json.dumps('\t'.join(str(c) for c in r)) for r in rows)
    return (f'// <assetmerge:{kind}> generated by the toolkit\'s AssetMerge.py{note}; rerun it instead of editing.\n'
            f'// Rows for the AssetMerge plugin: install with assetMergeWrite({func}()).\n'
            f'function {func}() {{\n'
            f'  return {{\n'
            f'    file: {json.dumps(file)},\n'
            f'    header: {json.dumps(chr(9).join(header))},\n'
            f'    rows: [\n{body}\n    ],\n'
            f'  }};\n'
            f'}}\n'
            f'// </assetmerge:{kind}>\n')


def write_block(mod_js, kind, rows, note=''):
    """Puts (or replaces) the generated rows block and the shared writer in mod.js."""
    with open(mod_js, encoding='utf-8') as f:
        text = f.read()
    for name, block in ((kind, js_block(kind, rows, note)), ('lib', LIB)):
        # Markers only count as whole lines written by this tool: a comment elsewhere that mentions
        # "<assetmerge:models>" must never become the start of a replaced range.
        pattern = re.compile(r"^// <assetmerge:%s> generated by the toolkit's AssetMerge\.py[^\n]*\n.*?^// </assetmerge:%s>\n?" % (name, name), re.S | re.M)
        found = pattern.findall(text)
        if len(found) > 1:
            raise ValueError(f'{mod_js}: {len(found)} <assetmerge:{name}> blocks; keep one')
        if found:
            body = found[0]
            if body.count('\nfunction ') > 1 or len(body) > 200000:
                raise ValueError(f'{mod_js}: the <assetmerge:{name}> block holds more than the generated code; not replaced')
            text = pattern.sub(lambda _: block, text, count=1)
        else:
            text = text.rstrip('\n') + '\n\n' + block
    with open(mod_js, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main(argv):
    parser = argparse.ArgumentParser(description='Fragment rows for the AssetMerge plugin.')
    sub = parser.add_subparsers(dest='command', required=True)
    m = sub.add_parser('models')
    m.add_argument('--mod', required=True)
    m.add_argument('--game', default=os.environ.get('D2R_PATH', r'D:\games\Steam\steamapps\common\Diablo II Resurrected'))
    m.add_argument('--casclib', default=os.environ.get('D2R_CASCLIB'))
    m.add_argument('--print', action='store_true')
    a = sub.add_parser('animdata')
    a.add_argument('--mod', required=True)
    a.add_argument('--rows', required=True)
    a.add_argument('--print', action='store_true')
    g = sub.add_parser('merge')
    g.add_argument('--models', nargs=2, required=True, metavar=('INDEX', 'FRAGMENT'))
    g.add_argument('--out', required=True)
    args = parser.parse_args(argv)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    if args.command == 'models':
        import ModelLodDesc
        manifest = ModelLodDesc.read_manifest(args.mod)
        if manifest is None:
            print(f'{args.mod}: no model_index.json')
            return 1
        rows = model_rows(args.mod, manifest['models'])
        from d2r_casc import D2RArchive
        with D2RArchive(args.game, args.casclib) as archive:
            check_models(archive, rows)
        if args.print:
            sys.stdout.write(fragment_text('models', rows))
            return 0
        write_block(os.path.join(args.mod, 'mod.js'), 'models', rows, ' from model_index.json')
        print(f"{len(rows)} model row(s) for {len({r[0] for r in rows})} model(s) written to mod.js")
        return 0
    if args.command == 'animdata':
        with open(args.rows, encoding='utf-8') as f:
            rows = [[r.get(k, '') for k in ANIMDATA_HEADER] for r in json.load(f)]
        if args.print:
            sys.stdout.write(fragment_text('animdata', rows))
            return 0
        write_block(os.path.join(args.mod, 'mod.js'), 'animdata', rows)
        print(f'{len(rows)} animdata row(s) written to mod.js')
        return 0
    import ModelLodDesc
    with open(args.models[0], 'rb') as f:
        desc = ModelLodDesc.ModelLodDesc(f.read())
    with open(args.models[1], encoding='utf-8') as f:
        lines = [l.rstrip('\r\n').split('\t') for l in f if l.strip()]
    rows = [l + [''] * (10 - len(l)) for l in lines[1:]]
    with open(args.out, 'wb') as f:
        f.write(apply_models(desc, rows).to_bytes())
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
