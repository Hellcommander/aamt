"""Recoloured copies of Diablo II: Resurrected HD missile effects.

An HD missile definition (hd/missiles/<name>.json) points at particle files
(.particles, a compiled binary). A particle file names its textures by path,
and most of an effect's colour comes from those textures: gradient maps and
colour sprites. This tool makes a new "look" from an existing effect:

  1. every texture the effect's particle files use is read; the ones stored
     uncompressed (RGBA8) or as BC1 / BC3 blocks are recoloured and written
     under a new file name of the same length;
  2. the particle files are copied under a new name with the texture paths
     swapped for the recoloured ones (same length, so nothing else in the
     binary moves);
  3. a manifest says which particle path became which, for the mod script.

Nothing is written to the game folder. Colour that is baked into the particle
file itself (a constant colour, not a texture) and BC4/BC5/BC7 textures are
left as they are; the report lists them.

usage:
  RecolorEffect.py --game <D2R folder> --preset <preset.json> --out <mod folder> [--patch-mod <mod.js>]
  RecolorEffect.py --game <D2R folder> --preset <preset.json> --audit
"""
import argparse
import colorsys
import json
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from d2r_casc import D2RArchive  # noqa: E402

MAGIC = b'<DE('
# Pixel formats seen in .texture headers (byte 4). Sizes checked against the mip table.
FMT_RGBA8 = 0x1F
FORMAT_NAMES = {0x1F: 'RGBA8'}
TEXTURE_PATH = re.compile(rb'data/hd/[A-Za-z0-9_/\-]+\.texture')
# A texture with fewer coloured pixels than this is a data ramp (alpha remap,
# fresnel, linear gradient): its channels are read as numbers, so it is left alone.
COLOURED_FRACTION = 0.05
MANIFEST_START = '// <recolor-manifest> generated by RecolorEffect.py, do not edit by hand'
MANIFEST_END = '// </recolor-manifest>'


# ---------------------------------------------------------------------------
# .texture files
# ---------------------------------------------------------------------------
class Texture:
    """Header: magic, format byte, width, height, depth, mip count, then per mip
    (size, offset relative to the offset field itself)."""

    def __init__(self, data):
        if data[:4] != MAGIC:
            raise ValueError('not a .texture file')
        self.data = bytearray(data)
        self.format = data[4]
        self.width, self.height = struct.unpack_from('<II', data, 8)
        self.mip_count = struct.unpack_from('<I', data, 28)[0]
        self.mips = []  # (offset, size, width, height)
        w, h = self.width, self.height
        for i in range(self.mip_count):
            pos = 36 + i * 8
            size, rel = struct.unpack_from('<II', data, pos)
            self.mips.append((pos + 4 + rel, size, w, h))
            w, h = max(1, w // 2), max(1, h // 2)

    def kind(self):
        """'rgba8', 'bc1', 'bc3', or None when the pixel data is not one this tool rewrites."""
        _, size, w, h = self.mips[0]
        blocks = max(1, (w + 3) // 4) * max(1, (h + 3) // 4)
        if self.format == FMT_RGBA8 and size == w * h * 4:
            return 'rgba8'
        return None if self.format == FMT_RGBA8 else self._block_kind(size, blocks)

    def _block_kind(self, size, blocks):
        # 8 bytes per block is BC1 (colour) or BC4 (one channel); 16 is BC3, BC5 or BC7.
        # They cannot be told apart by size, so block formats are only rewritten when
        # the preset names the format code: "blockFormats": {"<code>": "bc1" | "bc3"}.
        return None

    def describe(self):
        _, size, w, h = self.mips[0]
        blocks = max(1, (w + 3) // 4) * max(1, (h + 3) // 4)
        per_block = size / blocks
        name = FORMAT_NAMES.get(self.format, 'format 0x%02x (%g bytes per 4x4 block)' % (self.format, per_block))
        return '%dx%d %s, %d mips' % (self.width, self.height, name, self.mip_count)


def recolor_rgb(r, g, b, op):
    """r, g, b in 0..1 -> recoloured r, g, b."""
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    if 'hue' in op:  # colourise: every pixel takes this hue
        h = (op['hue'] % 360) / 360.0
        s = max(s, op.get('minSat', 0.0))
    h = (h + op.get('hueShift', 0) / 360.0) % 1.0
    s = min(1.0, s * op.get('sat', 1.0))
    v = min(1.0, v * op.get('value', 1.0))
    return colorsys.hsv_to_rgb(h, s, v)


def is_coloured(tex):
    """True when a real share of the first mip's pixels are not grey."""
    offset, size, _, _ = tex.mips[0]
    data = tex.data
    step = max(4, (size // 4 // 4096) * 4)  # sample about 4096 pixels
    coloured = total = 0
    for i in range(offset, offset + size, step):
        r, g, b = data[i], data[i + 1], data[i + 2]
        total += 1
        if max(r, g, b) - min(r, g, b) > 24:
            coloured += 1
    return total > 0 and coloured / total >= COLOURED_FRACTION


def recolor_rgba8(tex, op):
    cache = {}
    data = tex.data
    for offset, size, _, _ in tex.mips:
        for i in range(offset, offset + size, 4):
            key = bytes(data[i:i + 3])
            new = cache.get(key)
            if new is None:
                r, g, b = recolor_rgb(key[0] / 255.0, key[1] / 255.0, key[2] / 255.0, op)
                new = bytes((round(r * 255), round(g * 255), round(b * 255)))
                cache[key] = new
            data[i:i + 3] = new
    return bytes(data)


def _565(c):
    return ((c >> 11) & 31) / 31.0, ((c >> 5) & 63) / 63.0, (c & 31) / 31.0


def _to565(r, g, b):
    return (round(r * 31) << 11) | (round(g * 63) << 5) | round(b * 31)


def recolor_bc_color_block(data, pos, op, bc1):
    """Recolours the two RGB565 end points of a BC1-style colour block in place.
    In BC1 the order of the end points selects the block mode, so when
    recolouring flips it the end points are swapped and the 2-bit indices remapped."""
    c0, c1 = struct.unpack_from('<HH', data, pos)
    n0, n1 = _to565(*recolor_rgb(*_565(c0), op)), _to565(*recolor_rgb(*_565(c1), op))
    four = (c0 > c1) or not bc1
    idx = struct.unpack_from('<I', data, pos + 4)[0]
    if bc1 and four and n0 == n1:
        # Equal end points would turn a 4-colour block into a 3-colour one: nudge them apart.
        if n0 < 0xFFFF:
            n0 += 1
        else:
            n1 -= 1
    if bc1 and (n0 > n1) != four:
        n0, n1 = n1, n0
        if four:
            swap = (1, 0, 3, 2)  # c0<->c1, 2/3 c0<->2/3 c1
        else:
            swap = (1, 0, 2, 3)  # c0<->c1, midpoint and transparent stay
        out = 0
        for k in range(16):
            out |= swap[(idx >> (2 * k)) & 3] << (2 * k)
        idx = out
    struct.pack_into('<HHI', data, pos, n0, n1, idx)


def recolor_blocks(tex, op, kind):
    data = tex.data
    step, color_at = (8, 0) if kind == 'bc1' else (16, 8)
    for offset, size, _, _ in tex.mips:
        for pos in range(offset, offset + size - step + 1, step):
            recolor_bc_color_block(data, pos + color_at, op, kind == 'bc1')
    return bytes(data)


# ---------------------------------------------------------------------------
# Looks
# ---------------------------------------------------------------------------
def renamed(path, tag):
    """Same folder, same length: the first characters of the file name become the tag."""
    folder, name = path.rsplit('/', 1)
    if len(name) <= len(tag) + len('.texture'):
        raise ValueError('file name too short to tag: ' + path)
    return folder + '/' + tag + name[len(tag):]


def archive_key(path):
    return path[5:] if path.lower().startswith('data/') else path


def build_look(archive, look, preset, out_dir, report):
    block_formats = preset.get('blockFormats', {})
    skip_folders = ['/%s/' % d for d in preset.get('skipFolders', [])]
    tag = look['tag']
    source = look['source']
    definition = json.loads(archive.read('hd/missiles/%s.json' % source).decode('utf-8-sig'))
    entry = {'source': source, 'particles': {}, 'textures': [], 'recoloured': [], 'unchanged': []}
    particle_paths = [d['path'] for d in definition['dependencies'].get('particles', []) if d.get('path')]
    done = {}  # texture path -> new path, or None when left alone
    for ppath in particle_paths:
        blob = archive.read(archive_key(ppath))
        if blob is None:
            entry['unchanged'].append(ppath + ' (particle file not in the archive)')
            continue
        blob = bytearray(blob)
        swapped = 0
        for match in list(TEXTURE_PATH.finditer(bytes(blob))):
            tpath = match.group().decode('latin1')
            if tpath not in done:
                done[tpath] = None
                raw = archive.read(archive_key(tpath))
                if raw is None:
                    entry['unchanged'].append(tpath + ' (not in the archive)')
                else:
                    tex = Texture(raw)
                    kind = tex.kind() or block_formats.get('0x%02x' % tex.format)
                    if any(d in tpath for d in skip_folders):
                        new_bytes = None
                        entry['unchanged'].append('%s (folder skipped by the preset)' % tpath)
                    elif kind == 'rgba8' and not is_coloured(tex):
                        new_bytes = None
                        entry['unchanged'].append('%s (grey data ramp)' % tpath)
                    elif kind == 'rgba8':
                        new_bytes = recolor_rgba8(tex, look['color'])
                    elif kind in ('bc1', 'bc3'):
                        new_bytes = recolor_blocks(tex, look['color'], kind)
                    else:
                        new_bytes = None
                        entry['unchanged'].append('%s (%s)' % (tpath, tex.describe()))
                    if new_bytes is not None:
                        new_path = renamed(tpath, tag)
                        done[tpath] = new_path
                        entry['recoloured'].append('%s (%s)' % (tpath, tex.describe()))
                        entry['textures'].append(new_path)
                        if out_dir:
                            write(out_dir, new_path, new_bytes)
            if done[tpath]:
                blob[match.start():match.end()] = done[tpath].encode('latin1')
                swapped += 1
        if swapped:
            new_ppath = renamed(ppath, tag)
            entry['particles'][ppath] = new_ppath
            if out_dir:
                write(out_dir, new_ppath, bytes(blob))
    report[look['name']] = entry
    return entry


def write(out_dir, data_path, content):
    """data/hd/... -> <mod folder>/hd/..."""
    full = os.path.join(out_dir, archive_key(data_path).replace('/', os.sep))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'wb') as f:
        f.write(content)


def patch_mod(mod_js, manifest):
    with open(mod_js, 'r', encoding='utf-8') as f:
        text = f.read()
    block = '%s\nconst RECOLORED = %s;\n%s' % (MANIFEST_START, json.dumps(manifest, indent=2), MANIFEST_END)
    start, end = text.find(MANIFEST_START), text.find(MANIFEST_END)
    if start < 0 or end < 0:
        raise SystemExit('%s has no %s ... %s block' % (mod_js, MANIFEST_START, MANIFEST_END))
    with open(mod_js, 'w', encoding='utf-8', newline='') as f:
        f.write(text[:start] + block + text[end + len(MANIFEST_END):])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--game', default=os.environ.get('D2R_PATH'), help='folder that contains D2R.exe (or D2R_PATH)')
    ap.add_argument('--casclib', help='path of CascLib.dll (or D2R_CASCLIB)')
    ap.add_argument('--preset', required=True)
    ap.add_argument('--out', help='mod folder; files go under its hd folder')
    ap.add_argument('--patch-mod', help='mod.js whose recolor-manifest block is rewritten')
    ap.add_argument('--audit', action='store_true', help='report only, write nothing')
    args = ap.parse_args()
    if not args.game:
        raise SystemExit('pass --game or set D2R_PATH')
    if not args.audit and not args.out:
        raise SystemExit('pass --out <mod folder>, or --audit')
    with open(args.preset, 'r', encoding='utf-8') as f:
        preset = json.load(f)
    tags = [look['tag'] for look in preset['looks']]
    if len(set(tags)) != len(tags):
        raise SystemExit('every look needs its own tag')
    report = {}
    with D2RArchive(args.game, args.casclib) as archive:
        for look in preset['looks']:
            build_look(archive, look, preset, None if args.audit else args.out, report)
    manifest = {name: {'particles': e['particles'], 'textures': e['textures']} for name, e in report.items()}
    if not args.audit:
        with open(os.path.join(args.out, 'recolored_effects.report.json'), 'w', encoding='utf-8') as f:
            json.dump(report, f, indent=2)
        if args.patch_mod:
            patch_mod(args.patch_mod, manifest)
    for name, e in report.items():
        print('%s (from %s): %d particle file(s), %d texture(s) recoloured, %d left alone'
              % (name, e['source'], len(e['particles']), len(e['recoloured']), len(e['unchanged'])))
        if args.audit:
            for line in e['recoloured']:
                print('   recolour  ' + line)
            for line in e['unchanged']:
                print('   keep      ' + line)


if __name__ == '__main__':
    main()
